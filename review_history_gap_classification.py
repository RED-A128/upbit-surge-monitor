# ============================================================

def main() -> int:

    args = parse_args()

    try:

        return run_review(
            expected_full_markets=max(
                0,
                args.expected_full_markets,
            ),
            expected_full_jobs=max(
                0,
                args.expected_full_jobs,
            ),
            checkpoint_every=max(
                1,
                args.checkpoint_every,
            ),
            force=bool(
                args.force
            ),
        )

    except KeyboardInterrupt:

        print()
        print_line()

        print(
            "[INTERRUPTED] Review stopped "
            "by user."
        )

        print(
            "[RESUME] Successfully completed "
            "checkpoint entries remain "
            "available."
        )

        print(
            "[SAFETY] No source cleanup "
            "was executed."
        )

        print_line()

        return 130

    except Exception as exc:

        print()
        print_line()

        print(
            "HISTORY GAP CLASSIFICATION "
            "REVIEW FATAL ERROR"
        )

        print_line()

        print(
            f"{type(exc).__name__}: "
            f"{exc}"
        )

        print()

        print(
            "[SAFETY] No automatic source "
            "deletion was executed."
        )

        print(
            "[SAFETY] No Git reset/clean "
            "was executed."
        )

        print(
            "[RESUME] Successfully completed "
            "checkpoint entries remain "
            "available."
        )

        print_line()

        return 1


if __name__ == "__main__":
    sys.exit(main())
