def find_first_existing(
    candidates: Iterable[Path],
) -> Optional[Path]:

    for path in candidates:
        if path.exists() and path.is_file():
            return path

    return None


def discover_classifier_detail() -> Path:

    direct = find_first_existing(
        CLASSIFIER_DETAIL_CANDIDATES
    )

    if direct is not None:
        return direct

    found: list[Path] = []

    patterns = (
        "*classification*.csv",
        "*classifier*.csv",
        "*classified*gap*.csv",
    )

    for root in (
        DATA_DIR,
        REPORT_DIR,
        VALIDATION_DIR,
    ):
        if not root.exists():
            continue

        for pattern in patterns:
            for path in root.rglob(pattern):

                if not path.is_file():
                    continue

                if path in {
                    SUMMARY_PATH,
                    DETAIL_PATH,
                    STRUCTURAL_PATH,
                    REVIEW_PATH,
                    STATUS_PATH,
                    RECOVERABLE_PATH,
                }:
                    continue

                name = path.name.lower()

                if "summary" in name:
                    continue

                if "review" in name:
                    continue

                found.append(path)

    found = sorted(
        set(found),
        key=lambda p: (
            p.stat().st_mtime,
            str(p),
        ),
        reverse=True,
    )

    if not found:
        raise FileNotFoundError(
            "Classifier detail CSV was not found. "
            "Run classify_history_gaps.py first."
        )

    return found[0]


