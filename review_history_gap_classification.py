# 11. COLUMN RESOLUTION
# ============================================================

def resolve_column(
    df: pd.DataFrame,
    canonical_name: str,
    required: bool = False,
) -> Optional[str]:

    normalized_map = {
        normalize_column_name(str(column)):
        str(column)
        for column in df.columns
    }

    aliases = COLUMN_ALIASES.get(
        canonical_name,
        (canonical_name,),
    )

    for alias in aliases:

        key = normalize_column_name(alias)

        if key in normalized_map:
            return normalized_map[key]

    if required:
        raise RuntimeError(
            f"Required column not found: "
            f"{canonical_name}. "
            f"Available columns: "
            f"{list(df.columns)}"
        )

    return None


