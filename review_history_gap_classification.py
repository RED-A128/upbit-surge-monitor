def parse_args() -> argparse.Namespace:

    parser = argparse.ArgumentParser(
        description=(
            "Review History Gap "
            "Classification Clean V002"
        )
    )

    parser.add_argument(
        "--expected-full-markets",
        type=int,
        default=(
            DEFAULT_EXPECTED_FULL_MARKETS
        ),
        help=(
            "Expected unique markets in the "
            "FULL OHLCV source dataset. "
            "This is NOT the classifier "
            "market count. Use 0 to disable."
        ),
    )

    parser.add_argument(
        "--expected-full-jobs",
        type=int,
        default=(
            DEFAULT_EXPECTED_FULL_JOBS
        ),
        help=(
            "Expected market/timeframe jobs "
            "in the FULL OHLCV source "
            "dataset. This is NOT the "
            "classifier job count. "
            "Use 0 to disable."
        ),
    )

    parser.add_argument(
        "--checkpoint-every",
        type=int,
        default=10,
        help=(
            "Persist checkpoint every N "
            "newly processed gap jobs."
        ),
    )

    parser.add_argument(
        "--force",
        action="store_true",
        help=(
            "Revalidate every gap job even "
            "when a compatible checkpoint "
            "exists."
        ),
    )

    return parser.parse_args()


