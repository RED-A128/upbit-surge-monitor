    if not CHECKPOINT_PATH.exists():
        return None

    try:
        data = json.loads(
            CHECKPOINT_PATH.read_text(
                encoding="utf-8"
            )
        )

        if not isinstance(data, dict):
            return None

        return data

    except Exception:
        return None


