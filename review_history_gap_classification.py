def sha256_file(path: Path) -> str:
    hasher = hashlib.sha256()

    with path.open("rb") as f:
        while True:
            chunk = f.read(1024 * 1024)

            if not chunk:
                break

            hasher.update(chunk)

    return hasher.hexdigest()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def stable_json_bytes(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=True,
        sort_keys=True,
        separators=(",", ":"),
        default=str,
    ).encode("utf-8")


def dataframe_sha256(df: pd.DataFrame) -> str:
    if df.empty:
        return sha256_bytes(b"")

    normalized = df.copy()

    normalized = normalized.fillna("")

    columns = sorted(str(c) for c in normalized.columns)

    normalized.columns = [
        str(c)
        for c in normalized.columns
    ]

    normalized = normalized.reindex(columns=columns)

    sort_columns = [
        c
        for c in (
            "market",
            "timeframe",
            "gap_start",
            "gap_end",
            "classification",
        )
        if c in normalized.columns
    ]

    if sort_columns:
        normalized = normalized.sort_values(
            sort_columns,
            kind="stable",
        )

    csv_bytes = normalized.to_csv(
        index=False,
        lineterminator="\n",
    ).encode("utf-8")

    return sha256_bytes(csv_bytes)


def source_manifest_sha256(paths: Iterable[Path]) -> str:
    manifest: list[dict[str, Any]] = []

    for path in sorted(paths, key=lambda p: str(p).lower()):
        if not path.exists() or not path.is_file():
            continue

        stat = path.stat()

        manifest.append(
            {
                "path": str(path.relative_to(ROOT)),
                "size": stat.st_size,
                "sha256": sha256_file(path),
            }
        )

    return sha256_bytes(stable_json_bytes(manifest))


