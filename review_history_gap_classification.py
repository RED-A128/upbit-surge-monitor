def checkpoint_matches_input(
    checkpoint: Optional[
        dict[str, Any]
    ],
    input_fingerprint: str,
) -> bool:

    if checkpoint is None:
        return False

    if (
        checkpoint.get(
            "checkpoint_version"
        )
        != CHECKPOINT_VERSION
    ):
        return False

    if (
        checkpoint.get(
            "program_version"
        )
        != VERSION
    ):
        return False

    if (
        checkpoint.get(
            "input_fingerprint"
        )
        != input_fingerprint
    ):
        return False

    completed_jobs = checkpoint.get(
        "completed_jobs"
    )

    return isinstance(
        completed_jobs,
        dict,
    )


