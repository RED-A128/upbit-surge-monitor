def discover_ohlcv_files() -> list[Path]:
    files: list[Path] = []

    for timeframe in TIMEFRAMES:
        directory = OHLCV_DIR / timeframe

        if not directory.exists():
            continue

        files.extend(
            path
            for path in directory.glob("KRW-*.csv")
            if path.is_file()
        )

    return sorted(
        files,
        key=lambda p: str(p).lower(),
    )


