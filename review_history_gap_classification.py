def discover_ohlcv_files() -> list[Path]:

    files: list[Path] = []

    for timeframe in TIMEFRAMES:

        directory = OHLCV_DIR / timeframe

        if not directory.exists():
            continue

        files.extend(
            path
            for path in directory.glob(
                "KRW-*.csv"
            )
            if path.is_file()
        )

    return sorted(
        files,
        key=lambda p: str(p).lower(),
    )


def parse_ohlcv_identity(
    path: Path,
) -> tuple[str, str]:

    timeframe = path.parent.name.lower()
    market = path.stem.upper()

    return market, timeframe


def verify_full_ohlcv_coverage(
    ohlcv_files: list[Path],
    expected_full_markets: int,
    expected_full_jobs: int,
) -> dict[str, Any]:

    if not ohlcv_files:
        raise RuntimeError(
            "No OHLCV source files found."
        )

    identities: list[tuple[str, str]] = []

    for path in ohlcv_files:

        market, timeframe = (
            parse_ohlcv_identity(path)
        )

        if not market.startswith("KRW-"):
            raise RuntimeError(
                "Invalid OHLCV market filename: "
                + str(path)
            )

        if timeframe not in TIMEFRAMES:
            raise RuntimeError(
                "Invalid OHLCV timeframe directory: "
                + str(path)
            )

        identities.append(
            (market, timeframe)
        )

    if len(identities) != len(
        set(identities)
    ):
        raise RuntimeError(
            "Duplicate OHLCV market/timeframe "
            "identity detected."
        )

    markets = sorted(
        {
            market
            for market, _ in identities
        }
    )

    jobs = {
        f"{timeframe}|{market}"
        for market, timeframe in identities
    }

    timeframe_counts = {
        timeframe: sum(
            1
            for _, tf in identities
            if tf == timeframe
        )
        for timeframe in TIMEFRAMES
    }

    if expected_full_markets > 0:
        if len(markets) != (
            expected_full_markets
        ):
            raise RuntimeError(
                "Full OHLCV market count mismatch. "
                f"expected="
                f"{expected_full_markets}, "
                f"found={len(markets)}"
            )

    if expected_full_jobs > 0:
        if len(jobs) != expected_full_jobs:
            raise RuntimeError(
                "Full OHLCV job/file count mismatch. "
                f"expected={expected_full_jobs}, "
                f"found={len(jobs)}"
            )

    if expected_full_markets > 0:

        for timeframe in TIMEFRAMES:

            count = timeframe_counts[
                timeframe
            ]

            if count != expected_full_markets:
                raise RuntimeError(
                    "Full OHLCV timeframe coverage "
                    "mismatch. "
                    f"timeframe={timeframe}, "
                    f"expected="
                    f"{expected_full_markets}, "
                    f"found={count}"
                )

    return {
        "markets": markets,
        "market_count": len(markets),
        "job_count": len(jobs),
        "timeframe_counts": timeframe_counts,
    }


