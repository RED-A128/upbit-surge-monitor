def empty_checkpoint(
    input_fingerprint: str,
    classifier_path: Path,
    gap_report_path: Optional[Path],
) -> dict[str, Any]:
    return {
        "checkpoint_version": CHECKPOINT_VERSION,
        "program_version": VERSION,
        "created_at_utc": utc_now_iso(),
        "updated_at_utc": utc_now_iso(),
        "input_fingerprint": input_fingerprint,
        "classifier_path": str(
            classifier_path.relative_to(ROOT)
        ),
        "gap_report_path": (
            str(gap_report_path.relative_to(ROOT))
            if gap_report_path is not None
            else ""
        ),
        "completed_jobs": {},
    }


def load_checkpoint() -> Optional[dict[str, Any]]:
    if not CHECKPOINT_PATH.exists():
        return None

    try:
        data = json.loads(
            CHECKPOINT_PATH.read_text(
                encoding="utf-8"
            )
        )

        if not isinstance(data, dict):
            return None

        return data

    except Exception:
        return None


def save_checkpoint(
    checkpoint: dict[str, Any],
) -> None:
    checkpoint["updated_at_utc"] = utc_now_iso()

    atomic_write_json(
        CHECKPOINT_PATH,
        checkpoint,
    )


def checkpoint_matches_input(
    checkpoint: Optional[dict[str, Any]],
    input_fingerprint: str,
) -> bool:
    if checkpoint is None:
        return False

    if (
        checkpoint.get("checkpoint_version")
        != CHECKPOINT_VERSION
    ):
        return False

    if (
        checkpoint.get("program_version")
        != VERSION
    ):
        return False

    if (
        checkpoint.get("input_fingerprint")
        != input_fingerprint
    ):
        return False

    completed_jobs = checkpoint.get(
        "completed_jobs"
    )

    return isinstance(completed_jobs, dict)


