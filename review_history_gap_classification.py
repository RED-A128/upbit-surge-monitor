def build_job_summary(
    job_df: pd.DataFrame,
) -> ReviewJob:
    if job_df.empty:
        raise RuntimeError(
            "Cannot build summary for empty job."
        )

    markets = sorted(
        set(job_df["market"].tolist())
    )

    timeframes = sorted(
        set(job_df["timeframe"].tolist())
    )

    job_keys = sorted(
        set(job_df["job_key"].tolist())
    )

    if len(markets) != 1:
        raise RuntimeError(
            f"Job contains multiple markets: {markets}"
        )

    if len(timeframes) != 1:
        raise RuntimeError(
            "Job contains multiple timeframes: "
            f"{timeframes}"
        )

    if len(job_keys) != 1:
        raise RuntimeError(
            f"Job contains multiple keys: {job_keys}"
        )

    recoverable = job_df[
        job_df["classification"]
        == CLASS_RECOVERABLE
    ]

    structural = job_df[
        job_df["classification"]
        == CLASS_STRUCTURAL
    ]

    review = job_df[
        job_df["classification"]
        == CLASS_REVIEW
    ]

    return ReviewJob(
        job_key=job_keys[0],
        market=markets[0],
        timeframe=timeframes[0],
        row_count=len(job_df),
        recoverable_rows=len(recoverable),
        structural_rows=len(structural),
        review_rows=len(review),
        recoverable_missing=int(
            recoverable["missing_count"].sum()
        ),
        input_sha256=dataframe_sha256(job_df),
    )


def checkpoint_job_is_valid(
    stored: Any,
    current: ReviewJob,
) -> bool:
    if not isinstance(stored, dict):
        return False

    checks = (
        stored.get("job_key") == current.job_key,
        stored.get("market") == current.market,
        stored.get("timeframe") == current.timeframe,
        safe_int(stored.get("row_count"), -1)
        == current.row_count,
        safe_int(
            stored.get("recoverable_rows"),
            -1,
        )
        == current.recoverable_rows,
        safe_int(
            stored.get("structural_rows"),
            -1,
        )
        == current.structural_rows,
        safe_int(
            stored.get("review_rows"),
            -1,
        )
        == current.review_rows,
        safe_int(
            stored.get("recoverable_missing"),
            -1,
        )
        == current.recoverable_missing,
        stored.get("input_sha256")
        == current.input_sha256,
        stored.get("completed") is True,
    )

    return all(checks)


