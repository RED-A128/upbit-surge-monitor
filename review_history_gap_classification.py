def normalize_classifier_dataframe(
    raw_df: pd.DataFrame,
) -> pd.DataFrame:

    if raw_df.empty:
        raise RuntimeError(
            "Classifier detail CSV is empty."
        )

    market_col = resolve_column(
        raw_df,
        "market",
        required=True,
    )

    timeframe_col = resolve_column(
        raw_df,
        "timeframe",
        required=True,
    )

    class_col = resolve_column(
        raw_df,
        "classification",
        required=True,
    )

    gap_start_col = resolve_column(
        raw_df,
        "gap_start",
    )

    gap_end_col = resolve_column(
        raw_df,
        "gap_end",
    )

    missing_col = resolve_column(
        raw_df,
        "missing_count",
    )

    gap_seconds_col = resolve_column(
        raw_df,
        "gap_seconds",
    )

    reason_col = resolve_column(
        raw_df,
        "reason",
    )

    source_file_col = resolve_column(
        raw_df,
        "source_file",
    )

    normalized = pd.DataFrame()

    normalized["market"] = (
        raw_df[market_col]
        .map(normalize_market)
    )

    normalized["timeframe"] = (
        raw_df[timeframe_col]
        .map(normalize_timeframe)
    )

    normalized["classification"] = (
        raw_df[class_col]
        .map(normalize_classification)
    )

    normalized["gap_start"] = (
        raw_df[gap_start_col].map(normalize_text)
        if gap_start_col is not None
        else ""
    )

    normalized["gap_end"] = (
        raw_df[gap_end_col].map(normalize_text)
        if gap_end_col is not None
        else ""
    )

    normalized["missing_count"] = (
        raw_df[missing_col].map(safe_int)
        if missing_col is not None
        else 0
    )

    normalized["gap_seconds"] = (
        raw_df[gap_seconds_col].map(safe_int)
        if gap_seconds_col is not None
        else 0
    )

    normalized["reason"] = (
        raw_df[reason_col].map(normalize_text)
        if reason_col is not None
        else ""
    )

    normalized["source_file"] = (
        raw_df[source_file_col].map(normalize_text)
        if source_file_col is not None
        else ""
    )

    normalized["source_row"] = range(
        1,
        len(normalized) + 1,
    )

    invalid_market = (
        normalized["market"].eq("")
        | ~normalized["market"].str.startswith(
            "KRW-"
        )
    )

    if invalid_market.any():

        examples = normalized.loc[
            invalid_market,
            ["source_row", "market"],
        ].head(10).to_dict("records")

        raise RuntimeError(
            "Invalid classifier market values: "
            + json.dumps(
                examples,
                ensure_ascii=True,
            )
        )

    invalid_timeframe = (
        ~normalized["timeframe"].isin(
            TIMEFRAMES
        )
    )

    if invalid_timeframe.any():

        examples = normalized.loc[
            invalid_timeframe,
            ["source_row", "timeframe"],
        ].head(10).to_dict("records")

        raise RuntimeError(
            "Invalid classifier timeframe values: "
            + json.dumps(
                examples,
                ensure_ascii=True,
            )
        )

    invalid_class = (
        ~normalized["classification"].isin(
            VALID_CLASSES
        )
    )

    if invalid_class.any():

        examples = normalized.loc[
            invalid_class,
            [
                "source_row",
                "classification",
            ],
        ].head(20).to_dict("records")

        raise RuntimeError(
            "Unknown classification values detected. "
            "No unknown value will be silently "
            "converted. Examples: "
            + json.dumps(
                examples,
                ensure_ascii=True,
            )
        )

    if (
        normalized["missing_count"] < 0
    ).any():
        raise RuntimeError(
            "Negative classifier missing_count "
            "detected."
        )

    normalized["job_key"] = (
        normalized["timeframe"]
        + "|"
        + normalized["market"]
    )

    return normalized[
        [
            "source_row",
            "job_key",
            "market",
            "timeframe",
            "classification",
            "gap_start",
            "gap_end",
            "gap_seconds",
            "missing_count",
            "reason",
            "source_file",
        ]
    ]


