def read_csv_flexible(path: Path) -> pd.DataFrame:
    errors: list[str] = []

    for encoding in (
        "utf-8-sig",
        "utf-8",
        "cp949",
        "euc-kr",
    ):
        try:
            return pd.read_csv(
                path,
                encoding=encoding,
                low_memory=False,
            )
        except Exception as exc:
            errors.append(
                f"{encoding}: {type(exc).__name__}: {exc}"
            )

    raise RuntimeError(
        "Unable to read CSV file: "
        + str(path)
        + " | "
        + " | ".join(errors)
    )


