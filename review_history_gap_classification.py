# 16. OUTPUT INTEGRITY
# ============================================================

def verify_output_integrity(
    detail_df: pd.DataFrame,
    summary_df: pd.DataFrame,
    targets_df: pd.DataFrame,
    structural_df: pd.DataFrame,
    review_df: pd.DataFrame,
) -> None:
    total_split = (
        len(targets_df)
        + len(structural_df)
        + len(review_df)
    )

    if total_split != len(detail_df):
        raise RuntimeError(
            "Classification split row count mismatch. "
            f"detail={len(detail_df)}, "
            f"split={total_split}"
        )

    if not targets_df.empty:
        invalid_target = (
            targets_df[
                "approved_for_recovery"
            ] != True
        )

        if invalid_target.any():
            raise RuntimeError(
                "Recovery target approval integrity "
                "check failed."
            )

    expected_jobs = (
        detail_df["job_key"].nunique()
    )

    if len(summary_df) != expected_jobs:
        raise RuntimeError(
            "Summary job count mismatch. "
            f"expected={expected_jobs}, "
            f"found={len(summary_df)}"
        )

    duplicate_target_ids = (
        targets_df["target_id"].duplicated().any()
        if not targets_df.empty
        else False
    )

    if duplicate_target_ids:
        raise RuntimeError(
            "Duplicate recovery target_id detected."
        )


