def verify_classifier_against_gap_report(
    classifier_df: pd.DataFrame,
    gap_df: pd.DataFrame,
) -> dict[str, int]:

    classifier_markets = set(
        classifier_df["market"].unique()
    )

    gap_markets = set(
        gap_df["market"].unique()
    )

    classifier_jobs = set(
        classifier_df["job_key"].unique()
    )

    gap_jobs = set(
        gap_df["job_key"].unique()
    )

    if classifier_markets != gap_markets:

        missing = sorted(
            gap_markets - classifier_markets
        )

        extra = sorted(
            classifier_markets - gap_markets
        )

        raise RuntimeError(
            "Classifier market coverage mismatch "
            "against source gap report. "
            f"missing={missing[:20]}, "
            f"extra={extra[:20]}"
        )

    if classifier_jobs != gap_jobs:

        missing = sorted(
            gap_jobs - classifier_jobs
        )

        extra = sorted(
            classifier_jobs - gap_jobs
        )

        raise RuntimeError(
            "Classifier job coverage mismatch "
            "against source gap report. "
            f"missing={missing[:20]}, "
            f"extra={extra[:20]}"
        )

    classifier_signature = (
        build_event_signature(
            classifier_df
        )
        .value_counts()
        .sort_index()
    )

    gap_signature = (
        build_event_signature(
            gap_df
        )
        .value_counts()
        .sort_index()
    )

    if not classifier_signature.equals(
        gap_signature
    ):
        classifier_map = (
            classifier_signature.to_dict()
        )

        gap_map = gap_signature.to_dict()

        keys = sorted(
            set(classifier_map)
            | set(gap_map)
        )

        mismatches = []

        for key in keys:

            classifier_count = safe_int(
                classifier_map.get(key, 0)
            )

            gap_count = safe_int(
                gap_map.get(key, 0)
            )

            if classifier_count != gap_count:

                mismatches.append(
                    {
                        "signature": key,
                        "classifier": (
                            classifier_count
                        ),
                        "gap_report": (
                            gap_count
                        ),
                    }
                )

            if len(mismatches) >= 20:
                break

        raise RuntimeError(
            "Classifier gap-event coverage mismatch "
            "against source gap report. Examples: "
            + json.dumps(
                mismatches,
                ensure_ascii=True,
            )
        )

    return {
        "gap_markets": len(gap_markets),
        "gap_jobs": len(gap_jobs),
        "gap_events": len(gap_df),
    }


