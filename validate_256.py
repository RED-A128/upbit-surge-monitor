def validate_score_columns(
    df: pd.DataFrame,
    result: ValidationResult,
) -> None:
    found = [
        column
        for column in SCORE_COLUMNS
        if column in df.columns
    ]

    if not found:
        result.warn(
            "No expected score columns found."
        )
        return

    for column in found:
        series = pd.to_numeric(
            df[column],
            errors="coerce",
        )

        invalid = int(
            series.isna().sum()
        )

        if invalid:
            result.fail(
                f"Score '{column}' invalid/NaN values="
                f"{invalid:,}"
            )
            continue

        infinite = int(
            np.isinf(
                series.to_numpy(
                    dtype=float
                )
            ).sum()
        )

        if infinite:
            result.fail(
                f"Score '{column}' infinite values="
                f"{infinite:,}"
            )

    result.passed_message(
        "Expected score columns inspected."
    )


