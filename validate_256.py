def validate_timestamp_integrity(
    df: pd.DataFrame,
    label: str,
    result: ValidationResult,
) -> tuple[str | None, pd.Series | None]:
    timestamp_column = find_timestamp_column(df)

    if timestamp_column is None:
        result.fail(
            f"{label} has no supported timestamp column. "
            f"Expected one of: {TIMESTAMP_CANDIDATES}"
        )
        return None, None

    parsed = parse_timestamp_series(
        df[timestamp_column]
    )

    parse_failures = int(parsed.isna().sum())

    if parse_failures:
        result.fail(
            f"{label} timestamp parse failures="
            f"{parse_failures:,}"
        )
    else:
        result.passed_message(
            f"{label} timestamps parsed successfully."
        )

    valid = parsed.dropna()

    duplicate_count = int(
        valid.duplicated(keep=False).sum()
    )

    if duplicate_count:
        result.fail(
            f"{label} duplicate timestamps="
            f"{duplicate_count:,}"
        )
    else:
        result.passed_message(
            f"{label} timestamps are unique."
        )

    if len(valid) > 1:
        chronological = bool(
            valid.is_monotonic_increasing
        )

        if chronological:
            result.passed_message(
                f"{label} timestamps are chronological."
            )
        else:
            result.fail(
                f"{label} timestamps are not chronological."
            )
    else:
        result.passed_message(
            f"{label} timestamp chronology check passed."
        )

    if len(valid):
        first_timestamp = valid.iloc[0]
        last_timestamp = valid.iloc[-1]

        print(
            f"[INFO] {label} timestamp range: "
            f"{first_timestamp} -> {last_timestamp}"
        )

    return timestamp_column, parsed


