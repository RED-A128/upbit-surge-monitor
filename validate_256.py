def normalize_boolean_signal(
    series: pd.Series,
) -> tuple[pd.Series, list[str]]:
    """
    Return:
        boolean_series
        invalid_original_values

    Detector official state columns are expected to be
    binary-like values.
    """

    output = pd.Series(
        False,
        index=series.index,
        dtype=bool,
    )

    invalid_values: list[str] = []

    for index, value in series.items():
        if pd.isna(value):
            invalid_values.append("NaN")
            continue

        if isinstance(value, (bool, np.bool_)):
            output.at[index] = bool(value)
            continue

        if isinstance(
            value,
            (
                int,
                float,
                np.integer,
                np.floating,
            ),
        ):
            try:
                numeric_value = float(value)

                if math.isclose(
                    numeric_value,
                    1.0,
                    rel_tol=0.0,
                    abs_tol=1e-12,
                ):
                    output.at[index] = True
                    continue

                if math.isclose(
                    numeric_value,
                    0.0,
                    rel_tol=0.0,
                    abs_tol=1e-12,
                ):
                    output.at[index] = False
                    continue

                invalid_values.append(str(value))
                continue

            except Exception:
                invalid_values.append(str(value))
                continue

        text = str(value).strip().lower()

        if text in TRUE_VALUES:
            output.at[index] = True
            continue

        if text in FALSE_VALUES:
            output.at[index] = False
            continue

        invalid_values.append(str(value))

    return output, invalid_values


def validate_official_signal_states(
    df: pd.DataFrame,
    result: ValidationResult,
) -> dict[str, pd.Series]:
    missing = [
        column
        for column in OFFICIAL_STATE_COLUMNS
        if column not in df.columns
    ]

    if missing:
        result.fail(
            "Missing official detector state columns: "
            + ", ".join(missing)
        )
        return {}

    normalized: dict[str, pd.Series] = {}

    for column in OFFICIAL_STATE_COLUMNS:
        bool_series, invalid_values = (
            normalize_boolean_signal(
                df[column]
            )
        )

        normalized[column] = bool_series

        if invalid_values:
            unique_invalid = list(
                dict.fromkeys(invalid_values)
            )

            result.fail(
                f"Condition '{column}' has invalid "
                f"binary values: "
                f"{unique_invalid[:20]}"
            )
            continue

        true_count = int(
            bool_series.sum()
        )

        false_count = int(
            len(bool_series) - true_count
        )

        raw_values = (
            df[column]
            .astype(str)
            .drop_duplicates()
            .tolist()
        )

        print(
            f"[INFO] Condition '{column}': "
            f"true-like={true_count:,}, "
            f"false-like={false_count:,}, "
            f"values={raw_values[:20]}"
        )

    if len(normalized) == 3:
        result.setup_count = int(
            normalized["signal_setup"].sum()
        )

        result.ready_count = int(
            normalized["signal_ready"].sum()
        )

        result.trigger_count = int(
            normalized["signal_trigger"].sum()
        )

        result.passed_message(
            "Official SETUP / READY / TRIGGER "
            "columns validated."
        )

    return normalized


# ============================================================
# SIGNAL STAGE SUPPLEMENTARY INSPECTION
# ============================================================

def inspect_signal_stage(
    df: pd.DataFrame,
    official_states: dict[str, pd.Series],
    result: ValidationResult,
) -> None:
    """
    signal_stage is NOT used to calculate official counts.

    Official counts come only from:
        signal_setup
        signal_ready
        signal_trigger

    signal_stage is inspected for diagnostic purposes only.
    """

    if "signal_stage" not in df.columns:
        result.warn(
            "signal_stage column not present. "
            "Supplementary stage inspection skipped."
        )
        return

    stage = (
        df["signal_stage"]
        .fillna("")
        .astype(str)
        .str.strip()
    )

    counts = stage.value_counts(
        dropna=False
    )

    print("[INFO] signal_stage distribution:")

    for value, count in counts.head(30).items():
        display_value = (
            value if value else "<EMPTY>"
        )

        print(
            f"       {display_value}: {count:,}"
        )

    # Do NOT fail simply because stage labels do not equal
    # independent official-state counts.
    #
    # The detector can represent hierarchy / priority in
    # signal_stage while signal_setup, signal_ready and
    # signal_trigger remain independent binary research states.

    if official_states:
        result.passed_message(
            "signal_stage inspected separately from "
            "official state counts."
        )


# ============================================================
# FUTURE LEAKAGE INSPECTION
# ============================================================

def find_suspicious_future_columns(
    columns: Iterable[Any],
) -> list[str]:
    suspicious: list[str] = []

    for raw_column in columns:
        column = str(raw_column).strip()
        lower = column.lower()

        if column in ALLOWED_NEXT_COLUMNS:
            continue

        for pattern in FORBIDDEN_FUTURE_PATTERNS:
            if pattern in lower:
                suspicious.append(column)
                break

    return suspicious


def validate_future_leakage(
    feature: pd.DataFrame,
    signal: pd.DataFrame,
    result: ValidationResult,
) -> None:
    feature_suspicious = (
        find_suspicious_future_columns(
            feature.columns
        )
    )

    signal_suspicious = (
        find_suspicious_future_columns(
            signal.columns
        )
    )

    if feature_suspicious:
        result.fail(
            "Suspicious future/target Feature columns: "
            + ", ".join(feature_suspicious)
        )
    else:
        result.passed_message(
            "No suspicious future/target Feature "
            "columns detected."
        )

    if signal_suspicious:
        result.fail(
            "Suspicious future/target Signal columns: "
            + ", ".join(signal_suspicious)
        )
    else:
        result.passed_message(
            "No suspicious future/target Signal "
            "columns detected."
        )


# ============================================================
# SIGNAL -> OHLCV TIMESTAMP MEMBERSHIP
# ============================================================

def validate_signal_timestamp_membership(
    ohlcv_ts: pd.Series | None,
    signal_ts: pd.Series | None,
    result: ValidationResult,
) -> None:
    if (
        ohlcv_ts is None
        or signal_ts is None
    ):
        return

    valid_ohlcv = ohlcv_ts.dropna()
    valid_signal = signal_ts.dropna()

    ohlcv_set = set(
        valid_ohlcv.astype("int64").tolist()
    )

    signal_values = (
        valid_signal.astype("int64").tolist()
    )

    missing_count = sum(
        1
        for value in signal_values
        if value not in ohlcv_set
    )

    if missing_count:
        result.fail(
            "Signal timestamps missing from OHLCV="
            f"{missing_count:,}"
        )
    else:
        result.passed_message(
            "Every valid Signal timestamp exists in OHLCV."
        )


# ============================================================
# SOURCE HASH VALIDATION
# ============================================================

def validate_hash_unchanged(
    path: Path,
    before_hash: str | None,
    label: str,
    result: ValidationResult,
) -> None:
    if before_hash is None:
        result.fail(
            f"{label} SHA256 before-validation hash "
            "was unavailable."
        )
        return

    if not path.exists():
        result.fail(
            f"{label} disappeared during validation."
        )
        return

    try:
        after_hash = file_sha256(path)
    except Exception as exc:
        result.fail(
            f"{label} SHA256 after-validation failed: "
            f"{type(exc).__name__}: {exc}"
        )
        return

    if after_hash == before_hash:
        result.passed_message(
            f"{label} SHA256 unchanged."
        )
    else:
        result.fail(
            f"{label} SHA256 changed during validation."
        )


