def csv_markets(directory: Path) -> set[str]:
    if not directory.exists():
        return set()

    return {
        path.stem
        for path in directory.glob("KRW-*.csv")
        if path.is_file()
    }


def discover_markets() -> list[str]:
    """
    A market is considered valid for the full validator only
    when OHLCV / Feature / Signal files exist for ALL configured
    timeframes.

    We also report incomplete markets separately.
    """

    all_seen: set[str] = set()

    directory_sets: dict[str, set[str]] = {}

    for timeframe in TIMEFRAMES:
        for label, base_dir in (
            ("ohlcv", OHLCV_DIR),
            ("feature", FEATURE_DIR),
            ("signal", SIGNAL_DIR),
        ):
            key = f"{label}:{timeframe}"

            markets = csv_markets(
                base_dir / timeframe
            )

            directory_sets[key] = markets
            all_seen.update(markets)

    complete: list[str] = []

    for market in sorted(all_seen):
        exists_everywhere = True

        for timeframe in TIMEFRAMES:
            for label in (
                "ohlcv",
                "feature",
                "signal",
            ):
                key = f"{label}:{timeframe}"

                if market not in directory_sets[key]:
                    exists_everywhere = False
                    break

            if not exists_everywhere:
                break

        if exists_everywhere:
            complete.append(market)

    return complete


def discover_incomplete_markets(
    complete_markets: list[str],
) -> list[str]:
    complete_set = set(complete_markets)
    all_seen: set[str] = set()

    for timeframe in TIMEFRAMES:
        all_seen.update(
            csv_markets(
                OHLCV_DIR / timeframe
            )
        )
        all_seen.update(
            csv_markets(
                FEATURE_DIR / timeframe
            )
        )
        all_seen.update(
            csv_markets(
                SIGNAL_DIR / timeframe
            )
        )

    return sorted(
        all_seen - complete_set
    )


