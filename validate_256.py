def validate_unique_columns(
    df: pd.DataFrame,
    label: str,
    result: ValidationResult,
) -> None:
    duplicated = (
        pd.Index(df.columns)
        .duplicated(keep=False)
    )

    if duplicated.any():
        duplicates = (
            pd.Index(df.columns)[duplicated]
            .astype(str)
            .tolist()
        )

        result.fail(
            f"{label} duplicate column names: "
            f"{duplicates}"
        )
        return

    result.passed_message(
        f"{label} column names are unique."
    )


