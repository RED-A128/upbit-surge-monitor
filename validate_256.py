def safe_read_csv(
    path: Path,
    label: str,
    result: ValidationResult,
) -> pd.DataFrame | None:
    if not path.exists():
        result.fail(
            f"{label} file does not exist: {path}"
        )
        return None

    if not path.is_file():
        result.fail(
            f"{label} path is not a file: {path}"
        )
        return None

    result.passed_message(
        f"{label} file exists "
        f"({file_size_text(path)})"
    )

    try:
        df = pd.read_csv(
            path,
            low_memory=False,
        )

    except Exception as exc:
        result.fail(
            f"{label} CSV read failed: "
            f"{type(exc).__name__}: {exc}"
        )
        return None

    result.passed_message(
        f"{label} dataframe rows={len(df):,}, "
        f"columns={len(df.columns):,}"
    )

    return df


