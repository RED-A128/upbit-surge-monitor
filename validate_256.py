def separator(char: str = "-", length: int = 72) -> None:
    print(char * length)


def utc_now_text() -> str:
    return datetime.now(timezone.utc).isoformat()


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()

    with path.open("rb") as file:
        while True:
            block = file.read(1024 * 1024)

            if not block:
                break

            digest.update(block)

    return digest.hexdigest()


def file_size_text(path: Path) -> str:
    try:
        return f"{path.stat().st_size:,} bytes"
    except Exception:
        return "unknown size"


def normalize_column_name(value: Any) -> str:
    return str(value).strip()


def find_timestamp_column(df: pd.DataFrame) -> str | None:
    columns = {str(column).strip(): column for column in df.columns}

    for candidate in TIMESTAMP_CANDIDATES:
        if candidate in columns:
            return columns[candidate]

    return None


def safe_read_csv(
    path: Path,
    label: str,
    result: ValidationResult,
) -> pd.DataFrame | None:
    if not path.exists():
        result.fail(f"{label} file does not exist: {path}")
        return None

    if not path.is_file():
        result.fail(f"{label} path is not a file: {path}")
        return None

    result.passed_message(
        f"{label} file exists ({file_size_text(path)})"
    )

    try:
        df = pd.read_csv(
            path,
            low_memory=False,
        )
    except Exception as exc:
        result.fail(
            f"{label} CSV read failed: "
            f"{type(exc).__name__}: {exc}"
        )
        return None

    result.passed_message(
        f"{label} dataframe rows={len(df):,}, "
        f"columns={len(df.columns):,}"
    )

    return df


