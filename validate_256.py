def _numeric_timestamp_to_datetime(
    numeric: pd.Series,
) -> pd.Series:
    """
    Convert numeric timestamps using magnitude-aware Unix units.

    Typical values:

        seconds:
            1506311839

        milliseconds:
            1506311839886

        microseconds:
            1506311839886000

        nanoseconds:
            1506311839886000000

    Clean V002 specifically fixes the project OHLCV format:

        1506311839886.0

    which is Unix milliseconds.
    """

    result = pd.Series(
        pd.NaT,
        index=numeric.index,
        dtype="datetime64[ns, UTC]",
    )

    valid = numeric.notna()

    if not valid.any():
        return result

    absolute = numeric.abs()

    # Unix seconds.
    mask_seconds = (
        valid
        & (absolute < 1.0e11)
    )

    # Unix milliseconds.
    mask_milliseconds = (
        valid
        & (absolute >= 1.0e11)
        & (absolute < 1.0e14)
    )

    # Unix microseconds.
    mask_microseconds = (
        valid
        & (absolute >= 1.0e14)
        & (absolute < 1.0e17)
    )

    # Unix nanoseconds.
    mask_nanoseconds = (
        valid
        & (absolute >= 1.0e17)
    )

    if mask_seconds.any():
        result.loc[mask_seconds] = pd.to_datetime(
            numeric.loc[mask_seconds],
            unit="s",
            utc=True,
            errors="coerce",
        )

    if mask_milliseconds.any():
        result.loc[mask_milliseconds] = pd.to_datetime(
            numeric.loc[mask_milliseconds],
            unit="ms",
            utc=True,
            errors="coerce",
        )

    if mask_microseconds.any():
        result.loc[mask_microseconds] = pd.to_datetime(
            numeric.loc[mask_microseconds],
            unit="us",
            utc=True,
            errors="coerce",
        )

    if mask_nanoseconds.any():
        result.loc[mask_nanoseconds] = pd.to_datetime(
            numeric.loc[mask_nanoseconds],
            unit="ns",
            utc=True,
            errors="coerce",
        )

    return result


def parse_timestamp_series(
    series: pd.Series,
) -> pd.Series:
    """
    Robust timestamp parser.

    Handles:
        - Unix seconds
        - Unix milliseconds
        - Unix microseconds
        - Unix nanoseconds
        - Numeric values stored as strings
        - Numeric values stored with ".0"
        - ISO / datetime strings

    Numeric-looking values are parsed numerically first.
    Remaining values are parsed as datetime strings.
    """

    output = pd.Series(
        pd.NaT,
        index=series.index,
        dtype="datetime64[ns, UTC]",
    )

    if len(series) == 0:
        return output

    raw = series.copy()

    numeric = pd.to_numeric(
        raw,
        errors="coerce",
    )

    numeric_mask = numeric.notna()

    if numeric_mask.any():
        numeric_parsed = _numeric_timestamp_to_datetime(
            numeric
        )

        output.loc[numeric_mask] = numeric_parsed.loc[
            numeric_mask
        ]

    remaining_mask = output.isna() & raw.notna()

    if remaining_mask.any():
        string_values = (
            raw.loc[remaining_mask]
            .astype(str)
            .str.strip()
        )

        string_values = string_values.replace(
            {
                "": np.nan,
                "nan": np.nan,
                "NaN": np.nan,
                "None": np.nan,
                "null": np.nan,
                "NULL": np.nan,
            }
        )

        parsed_strings = pd.to_datetime(
            string_values,
            utc=True,
            errors="coerce",
        )

        output.loc[remaining_mask] = parsed_strings

    return output


