def _numeric_timestamp_to_datetime(
    numeric: pd.Series,
) -> pd.Series:
    result = pd.Series(
        pd.NaT,
        index=numeric.index,
        dtype="datetime64[ns, UTC]",
    )

    valid = numeric.notna()

    if not valid.any():
        return result

    absolute = numeric.abs()

    seconds = (
        valid
        & (absolute < 1.0e11)
    )

    milliseconds = (
        valid
        & (absolute >= 1.0e11)
        & (absolute < 1.0e14)
    )

    microseconds = (
        valid
        & (absolute >= 1.0e14)
        & (absolute < 1.0e17)
    )

    nanoseconds = (
        valid
        & (absolute >= 1.0e17)
    )

    if seconds.any():
        result.loc[seconds] = pd.to_datetime(
            numeric.loc[seconds],
            unit="s",
            utc=True,
            errors="coerce",
        )

    if milliseconds.any():
        result.loc[milliseconds] = pd.to_datetime(
            numeric.loc[milliseconds],
            unit="ms",
            utc=True,
            errors="coerce",
        )

    if microseconds.any():
        result.loc[microseconds] = pd.to_datetime(
            numeric.loc[microseconds],
            unit="us",
            utc=True,
            errors="coerce",
        )

    if nanoseconds.any():
        result.loc[nanoseconds] = pd.to_datetime(
            numeric.loc[nanoseconds],
            unit="ns",
            utc=True,
            errors="coerce",
        )

    return result


def parse_timestamp_series(
    series: pd.Series,
) -> pd.Series:
    output = pd.Series(
        pd.NaT,
        index=series.index,
        dtype="datetime64[ns, UTC]",
    )

    if len(series) == 0:
        return output

    raw = series.copy()

    numeric = pd.to_numeric(
        raw,
        errors="coerce",
    )

    numeric_mask = numeric.notna()

    if numeric_mask.any():
        parsed_numeric = (
            _numeric_timestamp_to_datetime(
                numeric
            )
        )

        output.loc[numeric_mask] = (
            parsed_numeric.loc[numeric_mask]
        )

    remaining = (
        output.isna()
        & raw.notna()
    )

    if remaining.any():
        strings = (
            raw.loc[remaining]
            .astype(str)
            .str.strip()
        )

        strings = strings.replace(
            {
                "": np.nan,
                "nan": np.nan,
                "NaN": np.nan,
                "None": np.nan,
                "null": np.nan,
                "NULL": np.nan,
            }
        )

        parsed_strings = pd.to_datetime(
            strings,
            utc=True,
            errors="coerce",
        )

        output.loc[remaining] = parsed_strings

    return output


