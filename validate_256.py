def normalize_boolean_signal(
    series: pd.Series,
) -> tuple[pd.Series, list[str]]:
    output = pd.Series(
        False,
        index=series.index,
        dtype=bool,
    )

    invalid_values: list[str] = []

    for index, value in series.items():
        if pd.isna(value):
            invalid_values.append("NaN")
            continue

        if isinstance(
            value,
            (bool, np.bool_),
        ):
            output.at[index] = bool(value)
            continue

        if isinstance(
            value,
            (
                int,
                float,
                np.integer,
                np.floating,
            ),
        ):
            try:
                numeric_value = float(value)

                if math.isclose(
                    numeric_value,
                    1.0,
                    rel_tol=0.0,
                    abs_tol=1e-12,
                ):
                    output.at[index] = True
                    continue

                if math.isclose(
                    numeric_value,
                    0.0,
                    rel_tol=0.0,
                    abs_tol=1e-12,
                ):
                    output.at[index] = False
                    continue

                invalid_values.append(
                    str(value)
                )
                continue

            except Exception:
                invalid_values.append(
                    str(value)
                )
                continue

        text = str(
            value
        ).strip().lower()

        if text in TRUE_VALUES:
            output.at[index] = True
            continue

        if text in FALSE_VALUES:
            output.at[index] = False
            continue

        invalid_values.append(
            str(value)
        )

    return output, invalid_values


def validate_official_signal_states(
    df: pd.DataFrame,
    result: ValidationResult,
) -> dict[str, pd.Series]:
    missing = [
        column
        for column in OFFICIAL_STATE_COLUMNS
        if column not in df.columns
    ]

    if missing:
        result.fail(
            "Missing official detector state columns: "
            + ", ".join(missing)
        )
        return {}

    normalized: dict[str, pd.Series] = {}

    for column in OFFICIAL_STATE_COLUMNS:
        bool_series, invalid_values = (
            normalize_boolean_signal(
                df[column]
            )
        )

        normalized[column] = bool_series

        if invalid_values:
            unique_invalid = list(
                dict.fromkeys(
                    invalid_values
                )
            )

            result.fail(
                f"Condition '{column}' has invalid "
                f"binary values: "
                f"{unique_invalid[:20]}"
            )
            continue

        true_count = int(
            bool_series.sum()
        )

        false_count = int(
            len(bool_series) - true_count
        )

        print(
            f"[INFO] Condition '{column}': "
            f"true-like={true_count:,}, "
            f"false-like={false_count:,}"
        )

    if len(normalized) == 3:
        result.setup_count = int(
            normalized[
                "signal_setup"
            ].sum()
        )

        result.ready_count = int(
            normalized[
                "signal_ready"
            ].sum()
        )

        result.trigger_count = int(
            normalized[
                "signal_trigger"
            ].sum()
        )

        result.passed_message(
            "Official SETUP / READY / TRIGGER "
            "columns validated."
        )

    return normalized


