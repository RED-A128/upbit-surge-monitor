def validate_hash_unchanged(
    path: Path,
    before_hash: str | None,
    label: str,
    result: ValidationResult,
) -> None:
    if before_hash is None:
        result.fail(
            f"{label} SHA256 before-validation hash "
            "was unavailable."
        )
        return

    if not path.exists():
        result.fail(
            f"{label} disappeared during validation."
        )
        return

    try:
        after_hash = file_sha256(
            path
        )

    except Exception as exc:
        result.fail(
            f"{label} SHA256 after-validation failed: "
            f"{type(exc).__name__}: {exc}"
        )
        return

    if after_hash == before_hash:
        result.passed_message(
            f"{label} SHA256 unchanged."
        )
    else:
        result.fail(
            f"{label} SHA256 changed during validation."
        )


