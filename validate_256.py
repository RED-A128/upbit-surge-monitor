def main() -> int:
    total_started = time.perf_counter()

    print()
    separator("=")
    print(
        f"{PROJECT_NAME} - {VALIDATOR_NAME}"
    )
    print(
        "STEP 4 - FULL KRW 256 DETECTOR OUTPUT VALIDATION"
    )
    separator("=")

    print(
        f"Started UTC : {utc_now_text()}"
    )
    print(
        f"Base dir    : {BASE_DIR}"
    )

    print()
    print("Mode:")
    print(
        "  READ ONLY validation"
    )
    print(
        "  FULL KRW market auto-discovery"
    )
    print(
        "  h1 / h4 / d1"
    )
    print(
        "  Resume / checkpoint enabled"
    )
    print(
        "  SHA256-aware resume"
    )
    print(
        "  Changed inputs are revalidated"
    )
    print(
        "  Failed jobs are retried"
    )
    print(
        "  Feature / Signal 1:1 verification"
    )
    print(
        "  Unix timestamp unit auto-detection"
    )
    print(
        "  SETUP / READY / TRIGGER inspection"
    )
    print(
        "  Future-information leakage check"
    )
    print(
        "  No future labels"
    )
    print(
        "  No prediction"
    )
    print(
        "  No trading"
    )

    if not validate_project_structure():
        print()
        separator("=")
        print(
            "[RESULT] PROJECT STRUCTURE FAILED"
        )
        print(
            "[STOP] Required data directories are missing."
        )
        return 1

    markets = discover_markets()

    incomplete = discover_incomplete_markets(
        markets
    )

    print()
    separator("=")
    print("MARKET DISCOVERY")
    separator("=")

    print(
        f"Complete markets : {len(markets):,}"
    )
    print(
        f"Expected jobs    : "
        f"{len(markets) * len(TIMEFRAMES):,}"
    )

    if incomplete:
        print(
            f"[FAIL] Incomplete markets detected: "
            f"{len(incomplete):,}"
        )

        for market in incomplete[:50]:
            print(
                f"       {market}"
            )

        if len(incomplete) > 50:
            print(
                f"       ... and "
                f"{len(incomplete) - 50:,} more"
            )

        print()
        print(
            "[STOP] Every KRW market must have "
            "OHLCV / Feature / Signal files for "
            "h1 / h4 / d1."
        )
        return 1

    if not markets:
        print(
            "[FAIL] No complete KRW markets discovered."
        )
        return 1

    if len(markets) != 290:
        print(
            f"[WARN] Current complete market count is "
            f"{len(markets):,}, not 290."
        )
        print(
            "[WARN] Validation will use the actual complete "
            "market set discovered from the data."
        )
    else:
        print(
            "[PASS] 290 complete KRW markets discovered."
        )

    checkpoint = load_checkpoint()

    results: list[ValidationResult] = []

    total_jobs = (
        len(markets)
        * len(TIMEFRAMES)
    )

    job_number = 0

    try:
        for market in markets:
            for timeframe in TIMEFRAMES:
                job_number += 1

                print()
                separator("=")
                print(
                    f"[JOB {job_number:,}/{total_jobs:,}] "
                    f"{market} {timeframe}"
                )
                separator("=")

                resume_ok, record = (
                    checkpoint_job_is_current(
                        checkpoint,
                        market,
                        timeframe,
                    )
                )

                if (
                    resume_ok
                    and record is not None
                ):
                    result = result_from_checkpoint(
                        market,
                        timeframe,
                        record,
                    )

                    results.append(
                        result
                    )

                    print(
                        f"[RESUME] SKIP {market} {timeframe}"
                    )
                    print(
                        "[PASS] Previous validation is still "
                        "valid and all input SHA256 hashes match."
                    )

                    continue

                try:
                    result = validate_one(
                        market=market,
                        timeframe=timeframe,
                    )

                except KeyboardInterrupt:
                    raise

                except Exception as exc:
                    (
                        ohlcv_path,
                        feature_path,
                        signal_path,
                    ) = get_job_paths(
                        market,
                        timeframe,
                    )

                    result = ValidationResult(
                        market=market,
                        timeframe=timeframe,
                        ohlcv_path=ohlcv_path,
                        feature_path=feature_path,
                        signal_path=signal_path,
                        passed=False,
                    )

                    message = (
                        "Unexpected validator exception: "
                        f"{type(exc).__name__}: {exc}"
                    )

                    result.errors.append(
                        message
                    )

                    print(
                        f"[FAIL] {message}"
                    )

                results.append(
                    result
                )

                if result.passed:
                    mark_checkpoint_passed(
                        checkpoint,
                        result,
                    )

                    print(
                        "[CHECKPOINT] PASS saved."
                    )
                else:
                    remove_failed_checkpoint_record(
                        checkpoint,
                        market,
                        timeframe,
                    )

                    print(
                        "[CHECKPOINT] Failed job was NOT "
                        "marked completed."
                    )

                write_status_csv(
                    results
                )

    except KeyboardInterrupt:
        print()
        separator("=")
        print(
            "[STOP] Validation interrupted by user."
        )
        print(
            "[PASS] Completed PASS jobs are already "
            "stored in the checkpoint."
        )
        print(
            "[PASS] Run the same validator again to resume."
        )
        print(
            f"Checkpoint : {CHECKPOINT_PATH}"
        )
        print(
            f"Completed this run : "
            f"{len(results):,}/{total_jobs:,}"
        )
        separator("=")

        try:
            write_status_csv(
                results
            )
        except Exception:
            pass

        return 130

    total_elapsed = (
        time.perf_counter()
        - total_started
    )

    write_status_csv(
        results
    )

    all_passed = print_summary(
        results,
        markets,
        total_elapsed,
    )

    if all_passed:
        checkpoint[
            "full_validation_passed"
        ] = True

        checkpoint[
            "full_validation_completed_utc"
        ] = utc_now_text()

        checkpoint[
            "market_count"
        ] = len(markets)

        checkpoint[
            "job_count"
        ] = len(results)

        save_checkpoint(
            checkpoint
        )

        return 0

    checkpoint[
        "full_validation_passed"
    ] = False

    save_checkpoint(
        checkpoint
    )

    return 1


