def validate_one(
    market: str,
    timeframe: str,
) -> ValidationResult:
    started = time.perf_counter()

    ohlcv_path = (
        OHLCV_DIR
        / timeframe
        / f"{market}.csv"
    )

    feature_path = (
        FEATURE_DIR
        / timeframe
        / f"{market}.csv"
    )

    signal_path = (
        SIGNAL_DIR
        / timeframe
        / f"{market}.csv"
    )

    result = ValidationResult(
        market=market,
        timeframe=timeframe,
        ohlcv_path=ohlcv_path,
        feature_path=feature_path,
        signal_path=signal_path,
    )

    separator("-")
    print(f"[{timeframe.upper()}] {market}")
    print(f"OHLCV  : {ohlcv_path}")
    print(f"Feature: {feature_path}")
    print(f"Signal : {signal_path}")
    print()

    # --------------------------------------------------------
    # SHA256 BEFORE
    # --------------------------------------------------------

    hashes_before: dict[str, str | None] = {
        "OHLCV": None,
        "Feature": None,
        "Signal": None,
    }

    for label, path in (
        ("OHLCV", ohlcv_path),
        ("Feature", feature_path),
        ("Signal", signal_path),
    ):
        if path.exists() and path.is_file():
            try:
                hashes_before[label] = (
                    file_sha256(path)
                )
            except Exception as exc:
                result.fail(
                    f"{label} SHA256 before-validation "
                    f"failed: {type(exc).__name__}: {exc}"
                )

    # --------------------------------------------------------
    # READ FILES
    # --------------------------------------------------------

    ohlcv = safe_read_csv(
        ohlcv_path,
        "OHLCV",
        result,
    )

    feature = safe_read_csv(
        feature_path,
        "Feature",
        result,
    )

    signal = safe_read_csv(
        signal_path,
        "Signal",
        result,
    )

    if (
        ohlcv is None
        or feature is None
        or signal is None
    ):
        result.elapsed_seconds = (
            time.perf_counter() - started
        )

        for label, path in (
            ("OHLCV", ohlcv_path),
            ("Feature", feature_path),
            ("Signal", signal_path),
        ):
            if path.exists():
                validate_hash_unchanged(
                    path,
                    hashes_before[label],
                    label,
                    result,
                )

        return result

    # --------------------------------------------------------
    # COLUMN NAME CHECK
    # --------------------------------------------------------

    validate_unique_columns(
        ohlcv,
        "OHLCV",
        result,
    )

    validate_unique_columns(
        feature,
        "Feature",
        result,
    )

    validate_unique_columns(
        signal,
        "Signal",
        result,
    )

    validate_required_ohlc_columns(
        ohlcv,
        result,
    )

    # --------------------------------------------------------
    # TIMESTAMP CHECK
    # --------------------------------------------------------

    _, ohlcv_ts = validate_timestamp_integrity(
        ohlcv,
        "OHLCV",
        result,
    )

    _, feature_ts = validate_timestamp_integrity(
        feature,
        "Feature",
        result,
    )

    _, signal_ts = validate_timestamp_integrity(
        signal,
        "Signal",
        result,
    )

    # --------------------------------------------------------
    # ROW / TIMESTAMP 1:1
    # --------------------------------------------------------

    validate_row_counts(
        ohlcv,
        feature,
        signal,
        result,
    )

    validate_timestamp_alignment(
        ohlcv_ts,
        feature_ts,
        signal_ts,
        result,
    )

    # --------------------------------------------------------
    # OHLCV SANITY
    # --------------------------------------------------------

    validate_ohlcv_values(
        ohlcv,
        result,
    )

    # --------------------------------------------------------
    # FEATURE / SIGNAL NUMERIC CHECK
    # --------------------------------------------------------

    validate_numeric_infinite_values(
        feature,
        "Feature",
        result,
    )

    validate_numeric_infinite_values(
        signal,
        "Signal",
        result,
    )

    # --------------------------------------------------------
    # MA CHECK
    # --------------------------------------------------------

    validate_ma_columns(
        signal,
        result,
    )

    # --------------------------------------------------------
    # SCORE CHECK
    # --------------------------------------------------------

    validate_score_columns(
        signal,
        result,
    )

    # --------------------------------------------------------
    # OFFICIAL RESEARCH STATES
    # --------------------------------------------------------

    official_states = (
        validate_official_signal_states(
            signal,
            result,
        )
    )

    # --------------------------------------------------------
    # SIGNAL STAGE
    # --------------------------------------------------------

    inspect_signal_stage(
        signal,
        official_states,
        result,
    )

    # --------------------------------------------------------
    # FUTURE LEAKAGE
    # --------------------------------------------------------

    validate_future_leakage(
        feature,
        signal,
        result,
    )

    # --------------------------------------------------------
    # SIGNAL TIMESTAMP MEMBERSHIP
    # --------------------------------------------------------

    validate_signal_timestamp_membership(
        ohlcv_ts,
        signal_ts,
        result,
    )

    # --------------------------------------------------------
    # SOURCE HASH AFTER
    # --------------------------------------------------------

    validate_hash_unchanged(
        ohlcv_path,
        hashes_before["OHLCV"],
        "OHLCV",
        result,
    )

    validate_hash_unchanged(
        feature_path,
        hashes_before["Feature"],
        "Feature",
        result,
    )

    validate_hash_unchanged(
        signal_path,
        hashes_before["Signal"],
        "Signal",
        result,
    )

    # --------------------------------------------------------
    # JOB SUMMARY
    # --------------------------------------------------------

    result.elapsed_seconds = (
        time.perf_counter() - started
    )

    print()
    print(
        f"Rows    : "
        f"OHLCV={result.ohlcv_rows:,} | "
        f"Feature={result.feature_rows:,} | "
        f"Signal={result.signal_rows:,}"
    )

    print(
        f"SETUP   : {result.setup_count:,}"
    )

    print(
        f"READY   : {result.ready_count:,}"
    )

    print(
        f"TRIGGER : {result.trigger_count:,}"
    )

    print(
        f"Elapsed : "
        f"{result.elapsed_seconds:.2f}s"
    )

    if result.passed:
        print("[RESULT] PASS")
    else:
        print("[RESULT] FAIL")

    return result


