def find_suspicious_future_columns(
    columns: Iterable[Any],
) -> list[str]:
    suspicious: list[str] = []

    for raw_column in columns:
        column = str(
            raw_column
        ).strip()

        lower = column.lower()

        if column in ALLOWED_NEXT_COLUMNS:
            continue

        for pattern in FORBIDDEN_FUTURE_PATTERNS:
            if pattern in lower:
                suspicious.append(
                    column
                )
                break

    return suspicious


def validate_future_leakage(
    feature: pd.DataFrame,
    signal: pd.DataFrame,
    result: ValidationResult,
) -> None:
    feature_suspicious = (
        find_suspicious_future_columns(
            feature.columns
        )
    )

    signal_suspicious = (
        find_suspicious_future_columns(
            signal.columns
        )
    )

    if feature_suspicious:
        result.fail(
            "Suspicious future/target Feature columns: "
            + ", ".join(
                feature_suspicious
            )
        )
    else:
        result.passed_message(
            "No suspicious future/target Feature "
            "columns detected."
        )

    if signal_suspicious:
        result.fail(
            "Suspicious future/target Signal columns: "
            + ", ".join(
                signal_suspicious
            )
        )
    else:
        result.passed_message(
            "No suspicious future/target Signal "
            "columns detected."
        )


