def validate_numeric_infinite_values(
    df: pd.DataFrame,
    label: str,
    result: ValidationResult,
) -> None:
    numeric_df = df.select_dtypes(
        include=[np.number]
    )

    if numeric_df.empty:
        result.passed_message(
            f"No numeric {label} columns require "
            "infinite-value inspection."
        )
        return

    values = numeric_df.to_numpy(
        dtype=float,
        copy=False,
    )

    infinite_count = int(
        np.isinf(values).sum()
    )

    if infinite_count:
        result.fail(
            f"{label} contains infinite numeric values="
            f"{infinite_count:,}"
        )
    else:
        result.passed_message(
            f"No infinite values found in numeric "
            f"{label} columns."
        )


