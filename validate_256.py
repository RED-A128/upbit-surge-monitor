def validate_row_counts(
    ohlcv: pd.DataFrame,
    feature: pd.DataFrame,
    signal: pd.DataFrame,
    result: ValidationResult,
) -> None:
    result.ohlcv_rows = len(ohlcv)
    result.feature_rows = len(feature)
    result.signal_rows = len(signal)

    if (
        result.ohlcv_rows
        == result.feature_rows
        == result.signal_rows
    ):
        result.passed_message(
            "OHLCV / Feature / Signal row counts are 1:1 "
            f"({result.signal_rows:,} rows)."
        )
    else:
        result.fail(
            "OHLCV / Feature / Signal row-count mismatch: "
            f"OHLCV={result.ohlcv_rows:,}, "
            f"Feature={result.feature_rows:,}, "
            f"Signal={result.signal_rows:,}"
        )


def validate_timestamp_alignment(
    ohlcv_ts: pd.Series | None,
    feature_ts: pd.Series | None,
    signal_ts: pd.Series | None,
    result: ValidationResult,
) -> None:
    if (
        ohlcv_ts is None
        or feature_ts is None
        or signal_ts is None
    ):
        result.fail(
            "Timestamp alignment could not be checked."
        )
        return

    if not (
        len(ohlcv_ts)
        == len(feature_ts)
        == len(signal_ts)
    ):
        result.fail(
            "Timestamp alignment skipped because "
            "row counts differ."
        )
        return

    if (
        ohlcv_ts.isna().any()
        or feature_ts.isna().any()
        or signal_ts.isna().any()
    ):
        result.fail(
            "Timestamp alignment cannot pass while "
            "parsed timestamps contain NaT."
        )
        return

    ohlcv_reset = ohlcv_ts.reset_index(
        drop=True
    )

    feature_equal = bool(
        ohlcv_reset.equals(
            feature_ts.reset_index(drop=True)
        )
    )

    signal_equal = bool(
        ohlcv_reset.equals(
            signal_ts.reset_index(drop=True)
        )
    )

    if feature_equal:
        result.passed_message(
            "Feature timestamps match OHLCV 1:1."
        )
    else:
        result.fail(
            "Feature timestamps do not match OHLCV 1:1."
        )

    if signal_equal:
        result.passed_message(
            "Signal timestamps match OHLCV 1:1."
        )
    else:
        result.fail(
            "Signal timestamps do not match OHLCV 1:1."
        )


