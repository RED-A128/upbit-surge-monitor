def numeric_series(
    df: pd.DataFrame,
    column: str,
) -> pd.Series:
    return pd.to_numeric(
        df[column],
        errors="coerce",
    )


def validate_ohlcv_values(
    df: pd.DataFrame,
    result: ValidationResult,
) -> None:
    missing = [
        column
        for column in REQUIRED_OHLC_COLUMNS
        if column not in df.columns
    ]

    if missing:
        return

    numeric = {
        column: numeric_series(
            df,
            column,
        )
        for column in REQUIRED_OHLC_COLUMNS
    }

    for column, series in numeric.items():
        invalid = int(
            series.isna().sum()
        )

        if invalid:
            result.fail(
                f"OHLCV {column} invalid/NaN values="
                f"{invalid:,}"
            )
        else:
            result.passed_message(
                f"OHLCV {column} numeric values valid."
            )

        values = series.to_numpy(
            dtype=float,
            na_value=np.nan,
        )

        non_finite = int(
            (~np.isfinite(values)).sum()
        )

        if non_finite:
            result.fail(
                f"OHLCV {column} non-finite values="
                f"{non_finite:,}"
            )

    open_price = numeric["open"]
    high_price = numeric["high"]
    low_price = numeric["low"]
    close_price = numeric["close"]
    volume = numeric["volume"]

    invalid_positive = (
        (open_price <= 0)
        | (high_price <= 0)
        | (low_price <= 0)
        | (close_price <= 0)
    )

    count = int(
        invalid_positive
        .fillna(True)
        .sum()
    )

    if count:
        result.fail(
            f"OHLCV non-positive price rows={count:,}"
        )
    else:
        result.passed_message(
            "OHLCV prices are positive."
        )

    negative_volume = int(
        (volume < 0)
        .fillna(False)
        .sum()
    )

    if negative_volume:
        result.fail(
            "OHLCV negative volume rows="
            f"{negative_volume:,}"
        )
    else:
        result.passed_message(
            "OHLCV volume is non-negative."
        )

    high_invalid = (
        (high_price < open_price)
        | (high_price < close_price)
        | (high_price < low_price)
    )

    high_count = int(
        high_invalid
        .fillna(False)
        .sum()
    )

    if high_count:
        result.fail(
            "OHLCV high relationship violations="
            f"{high_count:,}"
        )
    else:
        result.passed_message(
            "OHLCV high relationships are valid."
        )

    low_invalid = (
        (low_price > open_price)
        | (low_price > close_price)
        | (low_price > high_price)
    )

    low_count = int(
        low_invalid
        .fillna(False)
        .sum()
    )

    if low_count:
        result.fail(
            "OHLCV low relationship violations="
            f"{low_count:,}"
        )
    else:
        result.passed_message(
            "OHLCV low relationships are valid."
        )


