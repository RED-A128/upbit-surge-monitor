def is_ma_column(column: str) -> bool:
    lower = column.lower()

    for prefix in MA_PREFIXES:
        if lower.startswith(
            prefix + "_"
        ):
            return True

        if lower == prefix:
            return True

    return False


def validate_ma_columns(
    df: pd.DataFrame,
    result: ValidationResult,
) -> None:
    ma_columns = [
        str(column)
        for column in df.columns
        if is_ma_column(
            str(column)
        )
    ]

    if not ma_columns:
        result.warn(
            "No MA-prefixed columns found. "
            "MA validation skipped."
        )
        return

    failures = 0

    for column in ma_columns:
        series = pd.to_numeric(
            df[column],
            errors="coerce",
        )

        finite_values = series.dropna()

        # Important:
        # short-history markets can legitimately have an
        # entirely NaN SMA112/SMA224 warm-up column.
        if finite_values.empty:
            continue

        array = finite_values.to_numpy(
            dtype=float
        )

        infinite = int(
            np.isinf(array).sum()
        )

        if infinite:
            result.fail(
                f"MA column '{column}' infinite values="
                f"{infinite:,}"
            )
            failures += 1

    if failures == 0:
        result.passed_message(
            "MA columns passed finite-value validation."
        )


