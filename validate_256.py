def validate_signal_timestamp_membership(
    ohlcv_ts: pd.Series | None,
    signal_ts: pd.Series | None,
    result: ValidationResult,
) -> None:
    if (
        ohlcv_ts is None
        or signal_ts is None
    ):
        return

    valid_ohlcv = ohlcv_ts.dropna()
    valid_signal = signal_ts.dropna()

    ohlcv_set = set(
        valid_ohlcv
        .astype("int64")
        .tolist()
    )

    signal_values = (
        valid_signal
        .astype("int64")
        .tolist()
    )

    missing_count = sum(
        1
        for value in signal_values
        if value not in ohlcv_set
    )

    if missing_count:
        result.fail(
            "Signal timestamps missing from OHLCV="
            f"{missing_count:,}"
        )
    else:
        result.passed_message(
            "Every valid Signal timestamp exists in OHLCV."
        )


