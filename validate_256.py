def is_ma_column(column: str) -> bool:
    lower = column.lower()

    for prefix in MA_PREFIXES:
        if lower.startswith(prefix + "_"):
            return True

        if lower == prefix:
            return True

    return False


def validate_ma_columns(
    df: pd.DataFrame,
    result: ValidationResult,
) -> None:
    ma_columns = [
        str(column)
        for column in df.columns
        if is_ma_column(str(column))
    ]

    if not ma_columns:
        result.warn(
            "No MA-prefixed columns found. "
            "MA validation skipped."
        )
        return

    print(
        "[INFO] MA columns found: "
        + ", ".join(ma_columns)
    )

    failures = 0

    for column in ma_columns:
        series = pd.to_numeric(
            df[column],
            errors="coerce",
        )

        finite_values = series.dropna()

        if finite_values.empty:
            continue

        array = finite_values.to_numpy(
            dtype=float
        )

        infinite = int(
            np.isinf(array).sum()
        )

        if infinite:
            result.fail(
                f"MA column '{column}' infinite values="
                f"{infinite:,}"
            )
            failures += 1

        non_positive = int(
            (finite_values <= 0).sum()
        )

        # Some MA-like derived columns can legitimately be
        # ratios / directions. Therefore only warn.
        if non_positive:
            result.warn(
                f"MA-like column '{column}' has "
                f"{non_positive:,} non-positive values."
            )

    if failures == 0:
        result.passed_message(
            "MA columns passed finite-value validation."
        )


