def empty_checkpoint() -> dict[str, Any]:
    return {
        "checkpoint_version": CHECKPOINT_VERSION,
        "project": PROJECT_NAME,
        "validator": VALIDATOR_NAME,
        "validator_version": VERSION,
        "updated_utc": utc_now_text(),
        "completed": {},
    }


def load_checkpoint() -> dict[str, Any]:
    if not CHECKPOINT_PATH.exists():
        print(
            "[INFO] No previous validator checkpoint found."
        )
        return empty_checkpoint()

    try:
        with CHECKPOINT_PATH.open(
            "r",
            encoding="utf-8",
        ) as file:
            checkpoint = json.load(file)

    except Exception as exc:
        print(
            "[WARN] Previous checkpoint could not be read:"
        )
        print(
            f"       {type(exc).__name__}: {exc}"
        )
        print(
            "[WARN] Starting validation without trusting "
            "the old checkpoint."
        )

        return empty_checkpoint()

    if not isinstance(checkpoint, dict):
        print(
            "[WARN] Invalid checkpoint structure. "
            "Starting fresh."
        )
        return empty_checkpoint()

    if (
        checkpoint.get("checkpoint_version")
        != CHECKPOINT_VERSION
    ):
        print(
            "[WARN] Checkpoint version mismatch. "
            "Starting fresh."
        )
        return empty_checkpoint()

    completed = checkpoint.get("completed")

    if not isinstance(completed, dict):
        checkpoint["completed"] = {}

    print(
        "[PASS] Previous validator checkpoint loaded."
    )
    print(
        f"       Completed records: "
        f"{len(checkpoint['completed']):,}"
    )

    return checkpoint


def save_checkpoint(
    checkpoint: dict[str, Any],
) -> None:
    checkpoint["updated_utc"] = utc_now_text()

    atomic_write_json(
        CHECKPOINT_PATH,
        checkpoint,
    )


def job_key(
    market: str,
    timeframe: str,
) -> str:
    return f"{market}|{timeframe}"


def get_job_paths(
    market: str,
    timeframe: str,
) -> tuple[Path, Path, Path]:
    return (
        OHLCV_DIR
        / timeframe
        / f"{market}.csv",

        FEATURE_DIR
        / timeframe
        / f"{market}.csv",

        SIGNAL_DIR
        / timeframe
        / f"{market}.csv",
    )


def current_input_hashes(
    market: str,
    timeframe: str,
) -> dict[str, str] | None:
    ohlcv_path, feature_path, signal_path = (
        get_job_paths(
            market,
            timeframe,
        )
    )

    paths = {
        "ohlcv_sha256": ohlcv_path,
        "feature_sha256": feature_path,
        "signal_sha256": signal_path,
    }

    hashes: dict[str, str] = {}

    for key, path in paths.items():
        if not path.exists() or not path.is_file():
            return None

        try:
            hashes[key] = file_sha256(path)
        except Exception:
            return None

    return hashes


def checkpoint_job_is_current(
    checkpoint: dict[str, Any],
    market: str,
    timeframe: str,
) -> tuple[bool, dict[str, Any] | None]:
    key = job_key(
        market,
        timeframe,
    )

    record = checkpoint.get(
        "completed",
        {},
    ).get(key)

    if not isinstance(record, dict):
        return False, None

    if record.get("passed") is not True:
        return False, None

    current_hashes = current_input_hashes(
        market,
        timeframe,
    )

    if current_hashes is None:
        return False, None

    for hash_key, current_hash in current_hashes.items():
        if record.get(hash_key) != current_hash:
            print(
                f"[RESUME] {market} {timeframe}: "
                f"input changed -> revalidate"
            )
            return False, None

    return True, record


def result_from_checkpoint(
    market: str,
    timeframe: str,
    record: dict[str, Any],
) -> ValidationResult:
    ohlcv_path, feature_path, signal_path = (
        get_job_paths(
            market,
            timeframe,
        )
    )

    return ValidationResult(
        market=market,
        timeframe=timeframe,
        ohlcv_path=ohlcv_path,
        feature_path=feature_path,
        signal_path=signal_path,
        passed=True,
        ohlcv_rows=int(
            record.get("ohlcv_rows", 0)
        ),
        feature_rows=int(
            record.get("feature_rows", 0)
        ),
        signal_rows=int(
            record.get("signal_rows", 0)
        ),
        setup_count=int(
            record.get("setup_count", 0)
        ),
        ready_count=int(
            record.get("ready_count", 0)
        ),
        trigger_count=int(
            record.get("trigger_count", 0)
        ),
        elapsed_seconds=0.0,
        skipped_resume=True,
    )


def mark_checkpoint_passed(
    checkpoint: dict[str, Any],
    result: ValidationResult,
) -> None:
    hashes = current_input_hashes(
        result.market,
        result.timeframe,
    )

    if hashes is None:
        print(
            "[WARN] Could not create resume record because "
            "input hashes were unavailable."
        )
        return

    key = job_key(
        result.market,
        result.timeframe,
    )

    checkpoint.setdefault(
        "completed",
        {},
    )[key] = {
        "market": result.market,
        "timeframe": result.timeframe,
        "passed": True,
        "completed_utc": utc_now_text(),
        "ohlcv_rows": result.ohlcv_rows,
        "feature_rows": result.feature_rows,
        "signal_rows": result.signal_rows,
        "setup_count": result.setup_count,
        "ready_count": result.ready_count,
        "trigger_count": result.trigger_count,
        **hashes,
    }

    save_checkpoint(checkpoint)


def remove_failed_checkpoint_record(
    checkpoint: dict[str, Any],
    market: str,
    timeframe: str,
) -> None:
    key = job_key(
        market,
        timeframe,
    )

    completed = checkpoint.setdefault(
        "completed",
        {},
    )

    if key in completed:
        del completed[key]
        save_checkpoint(checkpoint)


