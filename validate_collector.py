def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Validate collector OHLCV data before or after backfill."
    )
    parser.add_argument(
        "--mode",
        choices=("pre", "post"),
        default="post",
        help=(
            "pre: allow markets missing from all h1/h4/d1 so backfill can create them; "
            "post: require complete current-market coverage"
        ),
    )
    return parser.parse_args()


# ============================================================
# MAIN VALIDATION
# ============================================================

def main() -> int:

    args = parse_args()
    validation_mode = args.mode.lower()

    print_header(
        "UPBIT SURGE MONITOR - "
        "COLLECTOR DATA VALIDATOR"
    )

    print(
        f"Project root       : {BASE_DIR}"
    )

    print(
        f"Data directory     : {DATA_DIR}"
    )

    print(
        f"OHLCV directory    : {OHLCV_DIR}"
    )

    print(
        "Timeframes         : h1 / h4 / d1"
    )

    print()
    print(
        f"Validation mode    : {validation_mode.upper()}"
    )

    print(
        "Mode               : READ ONLY"
    )

    print(
        "Source modification: DISABLED"
    )

    print(
        "Historical deletion: DISABLED"
    )

    # --------------------------------------------------------
    # LOAD CURRENT UPBIT KRW MARKET LIST
    # --------------------------------------------------------

    print()
    print_separator("-")
    print("CURRENT UPBIT KRW MARKET LIST")
    print_separator("-")

    try:

        current_market_list = (
            get_current_krw_markets()
        )

    except Exception as exc:

        print(
            "[FATAL] Failed to load current "
            "Upbit KRW market list."
        )

        print(
            f"{type(exc).__name__}: {exc}"
        )

        print_separator("=")

        return 1

    current_markets = set(
        current_market_list
    )

    print(
        "[PASS] Current Upbit KRW "
        "market list loaded."
    )

    print(
        f"Current KRW markets: "
        f"{len(current_markets):,}"
    )

    # --------------------------------------------------------
    # VERIFY BASE DIRECTORIES
    # --------------------------------------------------------

    if not DATA_DIR.exists():

        print()
        print(
            f"[FAIL] Data directory "
            f"not found: {DATA_DIR}"
        )

        return 1

    if not OHLCV_DIR.exists():

        print()
        print(
            f"[FAIL] OHLCV directory "
            f"not found: {OHLCV_DIR}"
        )

        return 1

    # --------------------------------------------------------
    # VALIDATE TIMEFRAMES
    # --------------------------------------------------------

    overall_errors: list[str] = []

    results: dict[
        str,
        TimeframeValidationResult,
    ] = {}

    for timeframe in (
        "h1",
        "h4",
        "d1",
    ):

        results[timeframe] = (
            validate_timeframe(
                timeframe=timeframe,
                directory=TIMEFRAME_DIRS[
                    timeframe
                ],
                current_markets=current_markets,
                enforce_current_coverage=(validation_mode == "post"),
            )
        )

    # --------------------------------------------------------
    # DIRECTORY / FILE VALIDATION RESULTS
    # --------------------------------------------------------

    for timeframe, result in results.items():

        if not result.directory_exists:

            overall_errors.append(
                f"{timeframe}: directory missing"
            )

        if (
            validation_mode == "post"
            and result.missing_current_markets
        ):
            overall_errors.append(
                f"{timeframe}: "
                f"{len(result.missing_current_markets):,} "
                "current KRW market files missing"
            )

        if result.failed_files > 0:

            overall_errors.append(
                f"{timeframe}: "
                f"{result.failed_files:,} "
                "invalid CSV files"
            )

    # --------------------------------------------------------
    # CURRENT MARKET COVERAGE
    # --------------------------------------------------------

    print()
    print_separator("-")
    print("CURRENT MARKET COVERAGE CHECK")
    print_separator("-")

    coverage_errors, allowed_new_markets = (
        validate_current_market_coverage(
            results=results,
            current_markets=current_markets,
            mode=validation_mode,
        )
    )

    if coverage_errors:

        print(
            "[FAIL] Current KRW market "
            "coverage problems: "
            f"{len(coverage_errors):,}"
        )

        for error in coverage_errors:

            print(
                f"  {error}"
            )

        overall_errors.extend(
            coverage_errors
        )

    else:

        if validation_mode == "pre" and allowed_new_markets:
            print(
                "[PASS] PRE mode accepted completely missing "
                "new current markets for backfill."
            )
            for market in allowed_new_markets:
                print(f"  [NEW MARKET] {market} -> h1/h4/d1 will be created by backfill")
        else:
            print(
                "[PASS] Every current Upbit KRW "
                "market exists in h1 / h4 / d1."
            )

    # --------------------------------------------------------
    # CROSS-TIMEFRAME MARKET SET
    # --------------------------------------------------------

    print()
    print_separator("-")
    print("CROSS-TIMEFRAME MARKET CHECK")
    print_separator("-")

    market_errors = compare_market_sets(
        results
    )

    if market_errors:

        print(
            "[FAIL] Market-set differences: "
            f"{len(market_errors):,}"
        )

        for error in market_errors:

            print(
                f"  {error}"
            )

        overall_errors.extend(
            market_errors
        )

    else:

        print(
            "[PASS] h1 / h4 / d1 contain "
            "the same stored market set."
        )

    # --------------------------------------------------------
    # SUMMARY
    # --------------------------------------------------------

    print_timeframe_summary(
        results=results,
        current_market_count=len(
            current_markets
        ),
    )

    failed_files = collect_failed_files(
        results
    )

    print_failed_file_summary(
        failed_files
    )

    print_historical_market_summary(
        results
    )

    total_files = calculate_total_files(
        results
    )

    total_rows = calculate_total_rows(
        results
    )

    passed_files = calculate_passed_files(
        results
    )

    failed_file_count = (
        calculate_failed_files(
            results
        )
    )

    historical_file_count = (
        calculate_historical_files(
            results
        )
    )

    print()
    print_separator("=")
    print("VALIDATION SUMMARY")
    print_separator("=")

    print(
        f"Project              : "
        f"{PROJECT_NAME}"
    )

    print(
        f"Version              : "
        f"{VERSION}"
    )

    print(
        f"Validation mode      : "
        f"{validation_mode.upper()}"
    )

    print(
        f"Current KRW markets  : "
        f"{len(current_markets):,}"
    )

    print(
        f"Expected active files: "
        f"{len(current_markets) * 3:,}"
    )

    print(
        f"Actual stored files  : "
        f"{total_files:,}"
    )

    print(
        f"Historical file refs : "
        f"{historical_file_count:,}"
    )

    print(
        f"Passed files         : "
        f"{passed_files:,}"
    )

    print(
        f"Failed files         : "
        f"{failed_file_count:,}"
    )

    print(
        f"Total OHLCV rows     : "
        f"{total_rows:,}"
    )

    print(
        f"Cross-market errors  : "
        f"{len(market_errors):,}"
    )

    print(
        f"Coverage errors      : "
        f"{len(coverage_errors):,}"
    )

    print(
        f"PRE allowed new mkts : "
        f"{len(allowed_new_markets):,}"
    )

    print(
        f"Overall errors       : "
        f"{len(overall_errors):,}"
    )

    print_separator("=")

    # --------------------------------------------------------
    # FINAL RESULT
    # --------------------------------------------------------

    if overall_errors:

        print(
            "[RESULT] COLLECTOR VALIDATION FAILED"
        )

        print()
        print(
            "Detected problems:"
        )

        for index, error in enumerate(
            overall_errors,
            start=1,
        ):

            print(
                f"  {index:03d}. {error}"
            )

        print_separator("=")

        return 1

    print(
        "[RESULT] COLLECTOR VALIDATION PASSED"
    )

    if validation_mode == "pre" and allowed_new_markets:
        print(
            "[PASS] Existing OHLCV data is valid enough to start backfill."
        )
        print(
            f"[INFO] {len(allowed_new_markets):,} completely missing current "
            "market(s) will be created by backfill."
        )
    else:
        print(
            "[PASS] All current Upbit KRW markets "
            "exist in h1 / h4 / d1."
        )

    print(
        "[PASS] All stored OHLCV CSV files "
        "passed validation."
    )

    if historical_file_count > 0:

        print(
            "[INFO] Historical/non-current "
            "market data was preserved."
        )

    print_separator("=")

    return 0


