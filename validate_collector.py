"""
Upbit Surge Monitor
Collector Data Validator

Version:
    Clean V002

File:
    validate_collector.py

Purpose:
    Validate OHLCV files generated by collector.py.

Main responsibilities:
    - Load the current Upbit KRW market list dynamically.
    - Validate h1 / h4 / d1 OHLCV CSV files.
    - Verify that every current KRW market exists in every timeframe.
    - Preserve historical CSV files for markets that are no longer active.
    - Detect invalid timestamps, duplicates, sorting problems,
      invalid OHLCV values, and invalid OHLC relationships.
    - Compare market sets across h1 / h4 / d1.
    - Never modify source OHLCV files.

Important:
    - This script NEVER modifies OHLCV source files.
    - Historical CSV files are never deleted.
    - Extra CSV files that are no longer in the current Upbit KRW
      market list are treated as historical data, not as errors.
    - Designed for Windows PC execution with:

          py validate_collector.py --mode pre
          py validate_collector.py --mode post

    PRE  : allow a market that is completely absent from h1/h4/d1
           (treated as a newly listed market waiting for backfill).
           Partial timeframe absence still fails.
    POST : require every current KRW market in h1/h4/d1.

Expected structure:

    data/
        ohlcv/
            h1/
            h4/
            d1/
        collector_status.csv
"""

