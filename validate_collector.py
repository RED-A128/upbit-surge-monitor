# MAIN VALIDATION
# ============================================================

def main() -> int:
    print_header("UPBIT SURGE MONITOR - COLLECTOR DATA VALIDATOR")

    print(f"Project root       : {BASE_DIR}")
    print(f"Data directory     : {DATA_DIR}")
    print(f"OHLCV directory    : {OHLCV_DIR}")
    print(f"Expected markets   : {EXPECTED_MARKET_COUNT:,}")
    print("Timeframes         : h1 / h4 / d1")
    print()
    print("Mode               : READ ONLY")
    print("Source modification: DISABLED")

    overall_errors: list[str] = []

    if not DATA_DIR.exists():
        print()
        print(f"[FAIL] Data directory not found: {DATA_DIR}")
        return 1

    if not OHLCV_DIR.exists():
        print()
        print(f"[FAIL] OHLCV directory not found: {OHLCV_DIR}")
        return 1

    results: dict[str, TimeframeValidationResult] = {}

    for timeframe in ("h1", "h4", "d1"):
        results[timeframe] = validate_timeframe(
            timeframe=timeframe,
            directory=TIMEFRAME_DIRS[timeframe],
        )

    # --------------------------------------------------------
    # Validate directory/file counts
    # --------------------------------------------------------

    for timeframe, result in results.items():
        if not result.directory_exists:
            overall_errors.append(
                f"{timeframe}: directory missing"
            )

        if result.file_count != result.expected_file_count:
            overall_errors.append(
                f"{timeframe}: "
                f"{result.file_count:,} files found, "
                f"{result.expected_file_count:,} expected"
            )

        if result.failed_files > 0:
            overall_errors.append(
                f"{timeframe}: "
                f"{result.failed_files:,} invalid files"
            )

    # --------------------------------------------------------
    # Compare markets between h1/h4/d1
    # --------------------------------------------------------

    print()
    print_separator("-")
    print("CROSS-TIMEFRAME MARKET CHECK")
    print_separator("-")

    market_errors = compare_market_sets(results)

    if market_errors:
        print(
            f"[FAIL] Market-set differences: "
            f"{len(market_errors):,}"
        )

        for error in market_errors:
            print(f"  {error}")

        overall_errors.extend(market_errors)

    else:
        print(
            "[PASS] h1 / h4 / d1 contain "
            "the same market set."
        )

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    print_timeframe_summary(results)

    failed_files = collect_failed_files(results)

    print_failed_file_summary(failed_files)

    total_files = calculate_total_files(results)
    total_rows = calculate_total_rows(results)
    passed_files = calculate_passed_files(results)
    failed_file_count = calculate_failed_files(results)

    print()
    print_separator("=")
    print("VALIDATION SUMMARY")
    print_separator("=")

    print(f"Project              : {PROJECT_NAME}")
    print(f"Version              : {VERSION}")
    print(f"Expected markets     : {EXPECTED_MARKET_COUNT:,}")
    print(f"Expected files       : {EXPECTED_MARKET_COUNT * 3:,}")
    print(f"Actual files         : {total_files:,}")
    print(f"Passed files         : {passed_files:,}")
    print(f"Failed files         : {failed_file_count:,}")
    print(f"Total OHLCV rows     : {total_rows:,}")
    print(f"Cross-market errors  : {len(market_errors):,}")
    print(f"Overall errors       : {len(overall_errors):,}")

    print_separator("=")

    if overall_errors:
        print("[RESULT] COLLECTOR VALIDATION FAILED")
        print()
        print("Detected problems:")

        for index, error in enumerate(
            overall_errors,
            start=1,
        ):
            print(f"  {index:03d}. {error}")

        print_separator("=")
        return 1

    print("[RESULT] COLLECTOR VALIDATION PASSED")
    print(
        "[PASS] All expected OHLCV files passed "
        "the validation checks."
    )
    print_separator("=")

    return 0


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    try:
        exit_code = main()

    except KeyboardInterrupt:
        print()
        print("[STOP] Validation interrupted by user.")
        exit_code = 130

    except Exception as exc:
        print()
        print_separator("=")
        print("VALIDATOR FATAL ERROR")
        print_separator("=")
        print(
            f"{type(exc).__name__}: {exc}"
        )
        print_separator("=")
        exit_code = 1

    sys.exit(exit_code)
