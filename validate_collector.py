def safe_text(value: Any) -> str:
    if value is None:
        return ""

    try:
        if pd.isna(value):
            return ""
    except Exception:
        pass

    return str(value)


# ============================================================
# HTTP
# ============================================================

def request_json(
    url: str,
    params: dict[str, Any] | None = None,
) -> Any:
    """
    Call Upbit REST API and return JSON.

    Temporary network errors, HTTP 429, and server errors
    are retried.
    """

    last_error: Exception | None = None

    for attempt in range(1, MAX_RETRIES + 1):

        try:
            response = SESSION.get(
                url,
                params=params,
                timeout=REQUEST_TIMEOUT,
            )

            if response.status_code == 429:
                wait_seconds = min(
                    float(attempt),
                    5.0,
                )

                print(
                    f"[WARN] HTTP 429 rate limit. "
                    f"retry={attempt}/{MAX_RETRIES}, "
                    f"wait={wait_seconds:.1f}s"
                )

                time.sleep(wait_seconds)
                continue

            if 500 <= response.status_code <= 599:
                wait_seconds = min(
                    float(attempt),
                    5.0,
                )

                print(
                    f"[WARN] Upbit server error "
                    f"{response.status_code}. "
                    f"retry={attempt}/{MAX_RETRIES}"
                )

                time.sleep(wait_seconds)
                continue

            response.raise_for_status()

            return response.json()

        except (
            requests.Timeout,
            requests.ConnectionError,
            requests.HTTPError,
            ValueError,
        ) as exc:

            last_error = exc

            if attempt >= MAX_RETRIES:
                break

            wait_seconds = min(
                float(attempt),
                5.0,
            )

            print(
                f"[WARN] Request failed: {exc} "
                f"retry={attempt}/{MAX_RETRIES}"
            )

            time.sleep(wait_seconds)

    if last_error is None:
        raise RuntimeError(
            "Unknown Upbit API request failure."
        )

    raise RuntimeError(
        f"Upbit API request failed after "
        f"{MAX_RETRIES} attempts: {last_error}"
    )


# ============================================================
# CURRENT UPBIT KRW MARKETS
# ============================================================

def get_current_krw_markets() -> list[str]:
    """
    Load the current KRW market list directly from Upbit.

    The validator intentionally does not use a fixed expected
    market count because listings and delistings can change.
    """

    url = f"{UPBIT_API_BASE}/market/all"

    data = request_json(
        url,
        params={
            "is_details": "false",
        },
    )

    if not isinstance(data, list):
        raise RuntimeError(
            "Unexpected Upbit market API response."
        )

    markets: list[str] = []

    for item in data:

        if not isinstance(item, dict):
            continue

        market = str(
            item.get("market", "")
        ).strip().upper()

        if market.startswith("KRW-"):
            markets.append(market)

    markets = sorted(set(markets))

    if not markets:
        raise RuntimeError(
            "No KRW markets were returned from Upbit."
        )

    return markets


