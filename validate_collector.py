def collect_failed_files(
    results: dict[str, TimeframeValidationResult],
) -> list[FileValidationResult]:

    failed: list[FileValidationResult] = []

    for timeframe_result in results.values():

        for file_result in timeframe_result.files:

            if not file_result.passed:

                failed.append(
                    file_result
                )

    return failed


def calculate_total_files(
    results: dict[str, TimeframeValidationResult],
) -> int:

    return sum(
        result.file_count
        for result in results.values()
    )


def calculate_total_rows(
    results: dict[str, TimeframeValidationResult],
) -> int:

    return sum(
        result.total_rows
        for result in results.values()
    )


def calculate_passed_files(
    results: dict[str, TimeframeValidationResult],
) -> int:

    return sum(
        result.passed_files
        for result in results.values()
    )


def calculate_failed_files(
    results: dict[str, TimeframeValidationResult],
) -> int:

    return sum(
        result.failed_files
        for result in results.values()
    )


def calculate_historical_files(
    results: dict[str, TimeframeValidationResult],
) -> int:

    return sum(
        result.historical_file_count
        for result in results.values()
    )


def print_timeframe_summary(
    results: dict[str, TimeframeValidationResult],
    current_market_count: int,
) -> None:

    print()
    print_separator("-")
    print("TIMEFRAME SUMMARY")
    print_separator("-")

    print(
        f"{'TF':<6}"
        f"{'FILES':>10}"
        f"{'CURRENT':>10}"
        f"{'EXPECTED':>10}"
        f"{'HIST':>8}"
        f"{'PASSED':>10}"
        f"{'FAILED':>10}"
        f"{'ROWS':>16}"
    )

    print_separator("-", 80)

    for timeframe in (
        "h1",
        "h4",
        "d1",
    ):

        result = results[timeframe]

        print(
            f"{timeframe.upper():<6}"
            f"{result.file_count:>10,}"
            f"{result.current_market_file_count:>10,}"
            f"{current_market_count:>10,}"
            f"{result.historical_file_count:>8,}"
            f"{result.passed_files:>10,}"
            f"{result.failed_files:>10,}"
            f"{result.total_rows:>16,}"
        )


def print_failed_file_summary(
    failed_files: list[FileValidationResult],
) -> None:

    if not failed_files:
        return

    print()
    print_separator("-")
    print("FAILED FILES")
    print_separator("-")

    for result in failed_files:

        print(
            f"[{result.timeframe.upper()}] "
            f"{result.market}"
        )

        print(
            f"  Path : {result.path}"
        )

        for error in result.errors:

            print(
                f"  ERROR: {error}"
            )

        for warning in result.warnings:

            print(
                f"  WARN : {warning}"
            )


def print_historical_market_summary(
    results: dict[str, TimeframeValidationResult],
) -> None:

    historical_union: set[str] = set()

    for result in results.values():

        historical_union.update(
            result.historical_markets
        )

    if not historical_union:
        return

    print()
    print_separator("-")
    print("HISTORICAL / NON-CURRENT MARKETS")
    print_separator("-")

    print(
        "These CSV files are preserved intentionally."
    )

    print(
        "They are not part of the current Upbit KRW "
        "market list and are NOT treated as validation errors."
    )

    print()

    for market in sorted(
        historical_union
    ):

        present_in: list[str] = []

        for timeframe in (
            "h1",
            "h4",
            "d1",
        ):

            result = results[
                timeframe
            ]

            markets = get_market_names(
                result
            )

            if market in markets:

                present_in.append(
                    timeframe
                )

        print(
            f"  {market:<18} "
            f"stored in: "
            f"{', '.join(present_in)}"
        )


