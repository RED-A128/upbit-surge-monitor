def normalize_column_name(column: str) -> str:
    return str(column).strip().lower()


def build_column_lookup(
    df: pd.DataFrame,
) -> dict[str, str]:

    lookup: dict[str, str] = {}

    for column in df.columns:

        normalized = normalize_column_name(
            column
        )

        if normalized not in lookup:
            lookup[normalized] = column

    return lookup


def find_timestamp_column(
    df: pd.DataFrame,
) -> str | None:

    lookup = build_column_lookup(df)

    for candidate in TIMESTAMP_CANDIDATES:

        if candidate in lookup:
            return lookup[candidate]

    return None


def find_required_column(
    df: pd.DataFrame,
    required_name: str,
) -> str | None:

    lookup = build_column_lookup(df)

    return lookup.get(required_name)


# ============================================================
# NUMERIC HELPERS
# ============================================================

def to_numeric_series(
    series: pd.Series,
) -> pd.Series:

    return pd.to_numeric(
        series,
        errors="coerce",
    )


def count_infinite_in_columns(
    df: pd.DataFrame,
    columns: list[str],
) -> int:

    total = 0

    for column in columns:

        numeric = to_numeric_series(
            df[column]
        )

        values = numeric.to_numpy(
            dtype=float,
            na_value=np.nan,
        )

        total += int(
            np.isinf(values).sum()
        )

    return total


# ============================================================
# TIMESTAMP VALIDATION
# ============================================================

def validate_timestamp(
    df: pd.DataFrame,
    result: FileValidationResult,
) -> pd.Series | None:

    timestamp_column = find_timestamp_column(
        df
    )

    if timestamp_column is None:

        result.passed = False

        result.errors.append(
            "Timestamp column not found. "
            f"Expected one of: "
            f"{', '.join(TIMESTAMP_CANDIDATES)}"
        )

        return None

    result.timestamp_column = timestamp_column

    timestamps = pd.to_datetime(
        df[timestamp_column],
        errors="coerce",
        utc=True,
    )

    result.invalid_timestamps = int(
        timestamps.isna().sum()
    )

    if result.invalid_timestamps > 0:

        result.passed = False

        result.errors.append(
            "Invalid timestamps: "
            f"{result.invalid_timestamps:,}"
        )

    valid_timestamps = timestamps.dropna()

    if valid_timestamps.empty:

        result.passed = False

        result.errors.append(
            "No valid timestamps found."
        )

        return timestamps

    result.first_timestamp = safe_text(
        valid_timestamps.min()
    )

    result.last_timestamp = safe_text(
        valid_timestamps.max()
    )

    result.duplicate_timestamps = int(
        valid_timestamps.duplicated(
            keep=False
        ).sum()
    )

    if result.duplicate_timestamps > 0:

        result.passed = False

        result.errors.append(
            "Duplicate timestamp rows: "
            f"{result.duplicate_timestamps:,}"
        )

    valid_array = valid_timestamps.reset_index(
        drop=True
    )

    if len(valid_array) >= 2:

        diff = valid_array.diff()

        result.unsorted_timestamps = int(
            (
                diff.iloc[1:]
                < pd.Timedelta(0)
            ).sum()
        )

        if result.unsorted_timestamps > 0:

            result.passed = False

            result.errors.append(
                "Timestamp order errors: "
                f"{result.unsorted_timestamps:,}"
            )

    return timestamps


# ============================================================
# REQUIRED COLUMN VALIDATION
# ============================================================

def validate_required_columns(
    df: pd.DataFrame,
    result: FileValidationResult,
) -> dict[str, str]:

    resolved: dict[str, str] = {}

    for required in REQUIRED_OHLC_COLUMNS:

        actual = find_required_column(
            df,
            required,
        )

        if actual is None:

            result.missing_required_columns.append(
                required
            )

        else:

            resolved[required] = actual

    if result.missing_required_columns:

        result.passed = False

        result.errors.append(
            "Missing required columns: "
            + ", ".join(
                result.missing_required_columns
            )
        )

    return resolved


# ============================================================
# NUMERIC OHLCV VALIDATION
# ============================================================

def validate_numeric_columns(
    df: pd.DataFrame,
    columns: dict[str, str],
    result: FileValidationResult,
) -> dict[str, pd.Series]:

    numeric: dict[str, pd.Series] = {}

    for logical_name, actual_name in columns.items():

        numeric[logical_name] = (
            to_numeric_series(
                df[actual_name]
            )
        )

    if "open" in numeric:

        result.nan_open = int(
            numeric["open"].isna().sum()
        )

        result.negative_open = int(
            (
                numeric["open"] < 0
            ).fillna(False).sum()
        )

    if "high" in numeric:

        result.nan_high = int(
            numeric["high"].isna().sum()
        )

        result.negative_high = int(
            (
                numeric["high"] < 0
            ).fillna(False).sum()
        )

    if "low" in numeric:

        result.nan_low = int(
            numeric["low"].isna().sum()
        )

        result.negative_low = int(
            (
                numeric["low"] < 0
            ).fillna(False).sum()
        )

    if "close" in numeric:

        result.nan_close = int(
            numeric["close"].isna().sum()
        )

        result.negative_close = int(
            (
                numeric["close"] < 0
            ).fillna(False).sum()
        )

    if "volume" in numeric:

        result.nan_volume = int(
            numeric["volume"].isna().sum()
        )

        result.negative_volume = int(
            (
                numeric["volume"] < 0
            ).fillna(False).sum()
        )

    nan_total = (
        result.nan_open
        + result.nan_high
        + result.nan_low
        + result.nan_close
        + result.nan_volume
    )

    negative_total = (
        result.negative_open
        + result.negative_high
        + result.negative_low
        + result.negative_close
        + result.negative_volume
    )

    if nan_total > 0:

        result.passed = False

        result.errors.append(
            "NaN/non-numeric OHLCV values: "
            f"{nan_total:,}"
        )

    if negative_total > 0:

        result.passed = False

        result.errors.append(
            "Negative OHLCV values: "
            f"{negative_total:,}"
        )

    actual_columns = list(
        columns.values()
    )

    if actual_columns:

        result.infinite_values = (
            count_infinite_in_columns(
                df,
                actual_columns,
            )
        )

        if result.infinite_values > 0:

            result.passed = False

            result.errors.append(
                "Infinite OHLCV values: "
                f"{result.infinite_values:,}"
            )

    return numeric


# ============================================================
# OHLC RELATIONSHIP VALIDATION
# ============================================================

def validate_ohlc_logic(
    numeric: dict[str, pd.Series],
    result: FileValidationResult,
) -> None:

    required = {
        "open",
        "high",
        "low",
        "close",
    }

    if not required.issubset(numeric):
        return

    open_series = numeric["open"]
    high_series = numeric["high"]
    low_series = numeric["low"]
    close_series = numeric["close"]

    result.invalid_high_low = int(
        (
            high_series < low_series
        ).fillna(False).sum()
    )

    result.invalid_high_open = int(
        (
            high_series < open_series
        ).fillna(False).sum()
    )

    result.invalid_high_close = int(
        (
            high_series < close_series
        ).fillna(False).sum()
    )

    result.invalid_low_open = int(
        (
            low_series > open_series
        ).fillna(False).sum()
    )

    result.invalid_low_close = int(
        (
            low_series > close_series
        ).fillna(False).sum()
    )

    invalid_total = (
        result.invalid_high_low
        + result.invalid_high_open
        + result.invalid_high_close
        + result.invalid_low_open
        + result.invalid_low_close
    )

    if invalid_total > 0:

        result.passed = False

        result.errors.append(
            "Invalid OHLC relationships: "
            f"{invalid_total:,}"
        )


# ============================================================
# MARKET COLUMN VALIDATION
# ============================================================

def validate_market_column(
    df: pd.DataFrame,
    expected_market: str,
    result: FileValidationResult,
) -> None:
    """
    If the CSV contains a market column, verify that it agrees
    with the filename.

    Example:
        KRW-BTC.csv -> market column must contain KRW-BTC.
    """

    lookup = build_column_lookup(df)

    market_column = lookup.get("market")

    if market_column is None:

        result.warnings.append(
            "Market column not found."
        )

        return

    values = (
        df[market_column]
        .dropna()
        .astype(str)
        .str.strip()
        .str.upper()
    )

    if values.empty:

        result.passed = False

        result.errors.append(
            "Market column contains no valid values."
        )

        return

    invalid_market_rows = int(
        (
            values != expected_market.upper()
        ).sum()
    )

    if invalid_market_rows > 0:

        result.passed = False

        result.errors.append(
            "Market column does not match filename: "
            f"{invalid_market_rows:,} rows"
        )


# ============================================================
# FILE VALIDATION
# ============================================================

def validate_file(
    timeframe: str,
    path: Path,
) -> FileValidationResult:

    result = FileValidationResult(
        timeframe=timeframe,
        market=path.stem.upper(),
        path=path,
    )

    try:

        if not path.exists():

            result.passed = False

            result.errors.append(
                "File does not exist."
            )

            return result

        if path.stat().st_size == 0:

            result.passed = False

            result.errors.append(
                "File is empty."
            )

            return result

        try:

            df = pd.read_csv(
                path,
                low_memory=False,
            )

        except Exception as exc:

            result.passed = False

            result.errors.append(
                "CSV read failed: "
                f"{type(exc).__name__}: {exc}"
            )

            return result

        result.row_count = len(df)

        if result.row_count == 0:

            result.passed = False

            result.errors.append(
                "CSV contains zero rows."
            )

            return result

        if len(df.columns) == 0:

            result.passed = False

            result.errors.append(
                "CSV contains zero columns."
            )

            return result

        validate_timestamp(
            df=df,
            result=result,
        )

        required_columns = (
            validate_required_columns(
                df=df,
                result=result,
            )
        )

        numeric = validate_numeric_columns(
            df=df,
            columns=required_columns,
            result=result,
        )

        validate_ohlc_logic(
            numeric=numeric,
            result=result,
        )

        validate_market_column(
            df=df,
            expected_market=path.stem.upper(),
            result=result,
        )

    except Exception as exc:

        result.passed = False

        result.errors.append(
            "Unexpected validation error: "
            f"{type(exc).__name__}: {exc}"
        )

    return result


# ============================================================
# TIMEFRAME VALIDATION
# ============================================================

def validate_timeframe(
    timeframe: str,
    directory: Path,
    current_markets: set[str],
    enforce_current_coverage: bool,
) -> TimeframeValidationResult:

    result = TimeframeValidationResult(
        timeframe=timeframe,
        directory=directory,
    )

    print()
    print_separator("-")
    print(
        f"VALIDATING TIMEFRAME: "
        f"{timeframe.upper()}"
    )
    print_separator("-")

    print(
        f"Directory       : {directory}"
    )

    if not directory.exists():

        result.errors.append(
            f"Directory not found: {directory}"
        )

        print(
            "[FAIL] Directory not found."
        )

        return result

    if not directory.is_dir():

        result.errors.append(
            f"Path is not a directory: {directory}"
        )

        print(
            "[FAIL] Path is not a directory."
        )

        return result

    result.directory_exists = True

    files = sorted(
        directory.glob("*.csv"),
        key=lambda item: item.name.upper(),
    )

    result.file_count = len(files)

    stored_markets = {
        path.stem.upper()
        for path in files
    }

    result.missing_current_markets = sorted(
        current_markets - stored_markets
    )

    result.historical_markets = sorted(
        stored_markets - current_markets
    )

    result.current_market_file_count = len(
        stored_markets & current_markets
    )

    result.historical_file_count = len(
        result.historical_markets
    )

    print(
        f"CSV files       : {result.file_count:,}"
    )

    print(
        f"Current markets : "
        f"{len(current_markets):,}"
    )

    print(
        f"Current files   : "
        f"{result.current_market_file_count:,}"
    )

    print(
        f"Historical files: "
        f"{result.historical_file_count:,}"
    )

    if result.missing_current_markets:

        if enforce_current_coverage:
            result.errors.append(
                "Missing current KRW market CSV files: "
                f"{len(result.missing_current_markets):,}"
            )
            print(
                "[FAIL] Missing current KRW market files: "
                f"{len(result.missing_current_markets):,}"
            )
        else:
            result.warnings.append(
                "Current KRW market CSV files not yet present: "
                f"{len(result.missing_current_markets):,}"
            )
            print(
                "[INFO] PRE mode - current KRW market files "
                "not yet present: "
                f"{len(result.missing_current_markets):,}"
            )

        for market in result.missing_current_markets:
            print(f"    [MISSING] {market}")

    else:

        print(
            "[PASS] Every current KRW market "
            "has a CSV file."
        )

    if result.historical_markets:

        result.warnings.append(
            "Historical/non-current market CSV files: "
            f"{len(result.historical_markets):,}"
        )

        print(
            "[INFO] Historical/non-current CSV files "
            "are preserved:"
        )

        for market in result.historical_markets:

            print(
                f"    [HISTORICAL] {market}"
            )

    if not files:

        result.errors.append(
            "No CSV files found."
        )

        print(
            "[FAIL] No CSV files found."
        )

        return result

    total_files = len(files)

    print()
    print(
        "Validating individual CSV files..."
    )
    print()

    for index, path in enumerate(
        files,
        start=1,
    ):

        file_result = validate_file(
            timeframe=timeframe,
            path=path,
        )

        result.files.append(
            file_result
        )

        result.total_rows += (
            file_result.row_count
        )

        if file_result.passed:

            result.passed_files += 1
            status = "OK"

        else:

            result.failed_files += 1
            status = "FAIL"

        market_type = (
            "CURRENT"
            if file_result.market in current_markets
            else "HIST"
        )

        print(
            f"[{index:03d}/{total_files:03d}] "
            f"{path.stem:<18} "
            f"{status:<4} "
            f"{market_type:<7} "
            f"rows={file_result.row_count:,}"
        )

        if not file_result.passed:

            for error in file_result.errors:

                print(
                    f"    [ERROR] {error}"
                )

        for warning in file_result.warnings:

            print(
                f"    [WARN ] {warning}"
            )

    print()
    print(
        f"[{timeframe.upper()}] "
        f"files={result.file_count:,} | "
        f"current={result.current_market_file_count:,} | "
        f"historical={result.historical_file_count:,} | "
        f"passed={result.passed_files:,} | "
        f"failed={result.failed_files:,} | "
        f"rows={result.total_rows:,}"
    )

    return result


